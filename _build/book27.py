h1(doc, "八、安全")
bullet(doc, "高温：1400℃ 以上的熔炉与炽热玻璃液，灼伤是第一位风险。工作区须划定并隔离无关人员。")
bullet(doc, "飞溅：熔融玻璃遇水会剧烈爆溅，坩埚、工具、地面必须绝对干燥。")
bullet(doc, "割伤：碎玻璃边缘锋利如刀，须备厚布与夹取工具，不得徒手捡。")
bullet(doc, "有毒添加物：铅、砷、汞、锑一类着色与澄清剂均有毒。称量时避免扬尘，废弃料单独掩埋。")
bullet(doc, "呼吸道：装料时的粉尘（尤其含硅粉尘）危害极大，湿法作业、戴湿布口罩。")
bullet(doc, "燃料：烧到 1400℃ 的窑燃料消耗惊人，先算清木炭供应量再点火，中途断火会导致整埚报废。")

h1(doc, "九、实施顺序建议")
bullet(doc, "第一步：先让窑稳定烧到 1400℃，用陶器试烧验证（册 04 的窑炉技术必须先过关）。")
bullet(doc, "第二步：小坩埚试熔，只求做出能拉丝、能压扁的玻璃块，不追求成品。")
bullet(doc, "第三步：做不透明或半透明的小件（珠、钮、釉料块），避开“透明”这个高难度要求。")
bullet(doc, "第四步：做吹制器皿；第五步：才考虑平板与镜子。")
bullet(doc, "全过程中，把每一埚的配方与火候都记下来——玻璃配方是最需要试错记录的一项技术。")

