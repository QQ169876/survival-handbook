h1(doc, "三、熔制：窑炉、坩埚与火候")
h2(doc, "① 窑炉")
bullet(doc, "结构：与册 04 的馒头窑同源，但要求更高——炉膛须长时间稳定在 1400~1500℃。")
bullet(doc, "坩埚：耐火黏土掺熟料（预烧碎陶）制成，须预先素烧并缓慢烘干，否则入炉即裂。")
bullet(doc, "燃料：木柴可行但耗量巨大；木炭火焰稳、温度高但更贵。窑炉是玻璃厂最大的固定成本。")
bullet(doc, "【经验】先建一台能稳定烧到 1400℃ 的窑，再谈玻璃。能烧陶不能烧玻璃，是常见的误判。")

h2(doc, "② 火候")
bullet(doc, "装料：先低温烘干预热，防止水分与碳酸盐放气时把料顶出坩埚。")
bullet(doc, "熔化：逐步升温，碳酸盐分解会放出大量气体，此时须慢，否则冒泡溢埚。")
bullet(doc, "澄清：到达熔融温度后保温一段时间，让气泡上浮排尽——这一步急不得。")
bullet(doc, "降温取料：熔体太稀不好操作，须降到黏度合适的“工作温度”再吹或浇。")
bullet(doc, "看火色判温（经验值）：橙黄约 1000℃，亮黄约 1200℃，亮黄白 1300~1400℃。"
            "这是无温度计条件下的唯一依据，须由老师傅带。")

h2(doc, "③ 退火——不做这步全废")
bullet(doc, "【科学】玻璃导热差，外冷内热会产生永久内应力，成品可能在几小时后自行炸裂，"
            "或一遇冷热变化就崩。")
bullet(doc, "做法：成型后的器物放入退火窑（又称退火炉），在退火区间保温，再用数小时到一昼夜缓慢降到常温。")
bullet(doc, "厚壁件退火时间要显著长于薄壁件；器皿底部与口沿的厚薄差越大，越容易在这一步裂。")

