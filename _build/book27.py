h2(doc, "① 吹制（器皿的主力）")
bullet(doc, "【史实】玻璃吹制技术约于公元前 1 世纪出现在东地中海沿岸，"
            "是古代玻璃从奢侈品变成日用品的分水岭。")
bullet(doc, "工具：铁吹管（一端有膨大的蘸料头）、铁顶杆（pontil）、木模与陶模、剪刀状工具。")
bullet(doc, "自由吹：蘸料 → 吹小泡 → 边转边整形 → 用工具夹、剪、拉出颈与口。")
bullet(doc, "模吹：把泡放进开合木模中吹足，花纹与形状一致，适合量产瓶与杯。")

h2(doc, "② 浇铸与压平（平板一）")
bullet(doc, "【史实】古代罗马已用浇铸法制作窗用平板玻璃，浇在平面上再研磨抛光。")
bullet(doc, "缺点：表面需长时间研磨抛光，费工；但设备要求最低，适合先做镜板与灯片。")

h2(doc, "③ 圆筒法（平板二）")
bullet(doc, "吹成长筒 → 趁热纵向剖开 → 入摊平炉摊成平板。")
bullet(doc, "【史实】此法在 19 世纪成为平板玻璃的主流工艺之一，幅面大、比浇铸省打磨。")
bullet(doc, "缺点：板面留有波筋与条纹，光学质量不高。")

h2(doc, "④ 冠冕法（平板三）")
bullet(doc, "吹泡后接到铁棒上，借离心力高速旋转甩成圆盘；中心留厚结（牛眼），边缘薄而亮。")
bullet(doc, "【史实】此法长期用于教堂彩色窗玻璃，成品有明显的旋纹与中心厚结。")
bullet(doc, "适合小块彩色窗，不适合大平板。")

