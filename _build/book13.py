h1(doc, "六、常见误区（这些做法会害死人）")
bullet(doc, "反复掀开敷料查看伤口——每掀一次就破坏一次凝血。压住不动，等足 10~15 分钟。")
bullet(doc, "往伤口上撒香灰、泥土、面粉——带入大量细菌，是感染与破伤风的直接来源。")
bullet(doc, "被蛇咬后切开、用嘴吸、喝酒、剧烈运动——全部加重损伤或加速毒素扩散。")
bullet(doc, "用细绳、铁丝当止血带——会造成神经与软组织不可逆损伤，等于自造截肢。")
bullet(doc, "焚烧雄黄驱蛇——生成砒霜，等于在自己营地上风处放毒。")
bullet(doc, "把食物放在帐篷里——气味会招来野兽，等于把自己当诱饵。")
bullet(doc, "见熊一律装死——不同种类反应不同，错误应对会失去逃生机会。")
bullet(doc, "伤口红肿仍只用草药外敷——感染进展时必须用分册一的青霉素，外敷救不了败血症。")

