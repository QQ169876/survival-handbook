h1(doc, "三、驱兽：火、圈、吊、选位")
figure(doc, os.path.join(IMG, "26_营地驱兽.png"), "图 13-3  营地布置与驱兽、遇兽应对")
h2(doc, "① 营地选址与布置")
bullet(doc, "选址：高燥、开阔、远离兽径与水源边；距水源 50~100 米（太近招兽，太远不便）；避开枯树、悬崖下、河滩。")
bullet(doc, "火：夜间至少保持一堆明火，理想是营区外围 2~3 堆，彼此可见。火是最可靠的驱兽手段。")
bullet(doc, "圈：营区外围撒一圈石灰或草木灰，蛇虫多数不愿跨越干燥的碱性粉带。")
bullet(doc, "吊：食物悬挂在离地 3 米以上、离树干 1.5 米以外的横杆上（防鼠、防熊、防猫科）。食物绝不放在住处内。")
bullet(doc, "垃圾与排泄物：远离营区掩埋，气味是最强的招兽信号。")
h2(doc, "② 驱兽手段（按可靠度排序）")
bullet(doc, "火：绝大多数野兽惧火，是唯一对所有兽类都有效的手段。")
bullet(doc, "噪声：铜锣、铁器敲击、齐声呼喊——对狼、野猪有效，但对习惯人声的个体效果递减，不能长期依赖。")
bullet(doc, "气味：辣椒 + 艾草烟熏刺激性最强；石灰圈对蛇虫有效；雄黄常温撒布（注意砷毒，见上文）。")
bullet(doc, "人尿：可标记领地，对部分中小型兽有威慑；但对虎豹等大型猫科无效，甚至可能吸引——别指望它。")
bullet(doc, "物理隔离：荆棘围栏、深沟、树上或高台宿营，是长期驻扎最稳的做法。")
h2(doc, "③ 遭遇应对")
bullet(doc, "狼群：不跑、不背对、结队正面相对、举火与敲击、慢慢后退。奔跑会激发追击本能。")
bullet(doc, "野猪：找树或巨石遮蔽；野猪冲刺基本是直线，在它贴近的瞬间侧身闪开。")
bullet(doc, "蛇：长杖打草惊蛇先行；不动的蛇多数不会主动攻击。被咬后：制动、伤肢低位固定、去掉戒指与束缚物、尽快接受处理；不切、不吸、不冰敷、不饮酒——这些都会加重损伤。")
bullet(doc, "蜂群：绝不拍打，蹲下用衣物护住头颈，逆风缓慢退离。")
bullet(doc, "熊：'装死'并非通用。先判断种类与距离，缓慢侧向退开，避免直视与突然动作。")
h2(doc, "④ 蛇药（有备无患）")
bullet(doc, "常见蛇药组方思路：七叶一枝花（重楼）、半边莲、白花蛇舌草、蚤休——多是清热解毒、消肿止痛之品。")
bullet(doc, "现实提醒：草药对毒蛇咬伤只能争取时间与缓解症状，不能中和毒素。真正的救治仍要靠制动、尽快排出与对症处理。")

