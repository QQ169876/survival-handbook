h1(doc, "四、三条校正（最容易出错的地方）")

h2(doc, "校正一：磁偏角——它指的不是正南北")
note(doc, "【史实·重要】沈括在《梦溪笔谈》中已记载磁针「常微偏东，不全南也」，"
          "这是世界上关于磁偏角的最早明确记载之一。\n"
          "【科学】地磁北极与地理北极并不重合，磁针指的是地磁方向，与正南北之间存在夹角，"
          "且这个夹角**因地而异、逐年变化**。")
bullet(doc, "做法：必须在当地用天文方法（正午日影、夜间北极星）定出真北，"
            "再量出磁针与之的夹角，把罗盘刻度按这个角度校正。")
bullet(doc, "每隔一段时间、或移动到较远的地方，都要重新校正。")
note(doc, "这是最容易被忽略、也最容易出大事的一条：不校正磁偏角，"
          "长距离行进会持续累积方向误差。")

h2(doc, "校正二：远离铁器")
bullet(doc, "【科学】铁器会扭曲局部磁场。铁锅、铁钉、刀剑、铁矿体、甚至含铁的岩石都会把针拉偏。")
bullet(doc, "做法：读数时清场，随身铁器放到数步之外；在疑似铁矿区域不要相信罗盘读数。")
bullet(doc, "判据：在同一地点把铁器移开后重读，若读数变化明显，说明有干扰。")

