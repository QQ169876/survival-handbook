h2(doc, "① 司南（【存疑】先看清楚）")
para(doc, "【史实】汉代文献中有「司南」的记载（如《论衡》：「司南之杓，投之于地，其柢指南」）。")
note(doc, "【存疑】司南的具体形制学界至今有争议——它究竟是不是一个磁性勺子、"
          "能不能真正稳定指向，缺乏出土实物佐证，现代复原品的指向效果也常被质疑。"
          "本册建议：**把司南当历史名词，不要当可靠器材去复原。**")

h2(doc, "② 指南鱼（记载明确，可复现）")
bullet(doc, "【史实】北宋《武经总要》记载了指南鱼的做法：把薄铁片剪成鱼形，"
            "烧红后按南北方向置入水中淬火（现代称为地磁淬火法），取出后浮于水面即可指南。")
bullet(doc, "【科学】其原理是：烧红的铁在居里温度以上失去磁性，"
            "沿地磁场方向迅速冷却时会被地磁场磁化（热剩磁）。这一原理在现代是可验证的。")
bullet(doc, "判据：淬火方向必须沿南北；淬后浮在水面，静止后首尾应稳定指向南北。反复测试确认。")

h2(doc, "③ 磁针（【史实】沈括的四种放置法）")
bullet(doc, "【史实】沈括《梦溪笔谈》记载了磁针的四种放置方式：浮于水面（水浮）、"
            "搁在碗唇上、搁在指甲上、用蚕丝悬挂（缕悬）。")
bullet(doc, "沈括本人评价：缕悬（悬丝）效果最好，因为摩擦最小；水浮次之，但最实用；"
            "碗唇与指甲易滑落，不可靠。")
bullet(doc, "推荐做法：日常用水浮法（碗中盛水，磁针穿一小段灯草或麦秆浮起）；"
            "需要精度时用悬丝法（用单根蚕丝悬住针的中部）。")

h2(doc, "④ 罗盘（针与方位盘合一）")
bullet(doc, "把磁针与刻有方位的圆盘结合即为罗盘。【史实】宋代已有关于指南针用于航海的明确记载——"
            "朱彧《萍洲可谈》：「舟师识地理，夜则观星，昼则观日，阴晦观指南针。」")
bullet(doc, "水罗盘（针浮在盘中的水上）与旱罗盘（针支在支轴上）两种形制。旱罗盘更适合携带。")
bullet(doc, "刻度：先定南北，再分四方位、八方位、二十四方位。刻度精度按需，不必一开始就做得太细。")

