bullet(doc, "看动物：清晨有鸟群盘旋低飞的方向、兽径的固定去向。")
bullet(doc, "挖井：选低洼处向下挖，见到湿沙后放缓，等水渗出再继续；井壁用砖石或木圈加固防塌。")

h2(doc, "③ 存水与输水")
