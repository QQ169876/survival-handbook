bullet(doc, "井要打在住处上游、厕所下游的反方向，且远离粪坑、牲畜圈、坟地。")
bullet(doc, "河岸取水点选在村落上游；若只能取下游水，必须煮沸。")

h2(doc, "② 找水的迹象")
