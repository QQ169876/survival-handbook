h1(doc, "〇、肥皂为什么是穿越第一产业")
para(doc, "肥皂是少数'原料遍地都是、技术一眼能懂、需求人人都有、利润立竿见影'的产业。"
          "它干净了你的手（降低感染率——比青霉素更基础的救命技术），还能卖钱建立信用。"
          "更重要的是：制皂的核心是'草木灰制碱'，这门手艺同时是玻璃、造纸、纺织的前置技术。")

h1(doc, "一、原理：一句话讲完皂化反应")
para(doc, "油脂 + 碱（KOH/NaOH）→ 脂肪酸盐（肥皂）+ 甘油。油脂是'憎水又亲油'的长链，"
          "变成脂肪酸盐后一头亲水一头亲油，把油污拉进水里冲走——这就是去污的原理。"
          "草木灰水里的碱是 KOH（碳酸钾），做出的皂偏软（软皂）；想得到硬皂（NaOH），需再用石灰'苛化'。")

h1(doc, "二、制碱：肥皂的全部门槛都在这一步")
figure(doc, os.path.join(IMG, "03_草木灰淋滤.png"), "图 2-1  草木灰淋滤制碱液")
h2(doc, "1. 草木灰淋滤（制 KOH / K₂CO₃ 溶液）")
bullet(doc, "灰要选硬木灰（栎、柞、桑），碱含量最高；稻草灰次之；煤灰完全没用。")
bullet(doc, "桶底钻孔铺稻草，灰压实（防短路），缓慢浇清水，下口接滤液。")
bullet(doc, "浓度用鸡蛋法检验：鸡蛋露出硬币大小即合适；过稀回淋，过浓加水。")
h2(doc, "2. 石灰苛化（把 K₂CO₃ 变成真正的 KOH，并可得少量硬皂）")
bullet(doc, "滤液煮沸，加入熟石灰（石灰石烧成的生石灰加水消化）约为灰量的 1/10，搅拌煮 1 小时。")
bullet(doc, "静置澄清，取上层清液——这才是强碱液。底部白色沉淀是碳酸钙，滤出可回窑重烧。")
h2(doc, "3. 想要硬皂（NaOH）")
para(doc, "用天然碱（盐湖碱土/口碱，主要成分 Na₂CO₃）代替草木灰同法苛化，即得 NaOH。"
          "沿海地区可直接熬盐卤尾料试用。没有天然碱就先做软皂——软皂同样是肥皂，古人照样买单。")
note(doc, "碱液强腐蚀：操作戴手套（多层布浸油亦可），溅眼立刻清水冲。装碱液的容器标记清楚，千万别当水喝。")

h1(doc, "三、油脂：有什么用什么")
table(doc, ["油脂", "成皂特性", "建议占比"],
      [["猪油/牛油/羊油", "泡沫中等，皂体硬（需NaOH），去污好", "主油 50~70%"],
       ["菜籽油", "软皂，泡沫少但去污力强", "主油或掺配"],
       ["芝麻油/豆油", "中性，保湿度好，贵", "掺配 20~30%"],
       ["椰子油（南方）", "泡沫丰富、去污猛", "掺配 10~20%"],
       ["桐油", "皂化快但成膜发黏，去污差", "不推荐做皂（留着做漆/防水）"],
       ["地沟油/渣油", "先熬炼去渣脱色（加白土/木炭煮沸过滤）", "可用，香皂不用"]],
      widths=None)
para(doc, "经验配比（软皂，草木灰碱液）：猪油或菜籽油 10 斤，配'鸡蛋法'标准浓度的碱液约 12~14 斤。"
          "油脂与碱的准确比例因油而异，宁少勿多——碱过量成品烧手，油过量成品软腻不出泡。")

h1(doc, "四、煮皂：一次说清全程")
bullet(doc, "① 熬油：油脂入锅小火熬开，捞渣去杂，离火稍晾。")
bullet(doc, "② 兑碱：碱液分 5~6 次缓缓加入热油（60~70℃，锅边起细泡不冒烟），边加边朝一个方向猛搅。")
bullet(doc, "③ 皂化：小火保持微沸 2~4 小时，不停搅拌防糊底。混合物先浑浊分离 → 逐渐变稠成糊——'皂化中'。")
bullet(doc, "④ 判断：挑一滴糊在舌侧尝（吐掉漱口），微涩不刺 = 恰好；剧痛烧舌 = 碱多，补油再煮；油腥 = 油多，补碱。")
bullet(doc, "⑤ 盐析（硬皂必做）：撒入食盐（约为糊量 5%）搅匀，皂块上浮与废液（甘油+杂碱）分层，捞出皂块。")
bullet(doc, "⑥ 压模晾熟：趁热压入木模（铺湿布），晾 1~2 天脱模切条，再阴干熟成 4~6 周（熟化期碱度下降，才不烧手）。")
h2(doc, "成熟度检验")
bullet(doc, "舌尝：不涩不烧 = 熟好（每次尝完必须漱口）。")
bullet(doc, "拉丝：切面光滑细腻、遇水起泡丰富即成。")
bullet(doc, "植物指示剂：紫草/牵牛花汁泡纸晾干做成'试纸'，遇碱变蓝绿——熟皂不显蓝绿。")

h1(doc, "五、香皂：同一个锅，卖十倍的价")
h2(doc, "香皂的三条升级路线")
bullet(doc, "好油打底：换芝麻油/猪油+椰子油，熟成后研碎回锅重制（研磨皂），质地细密如脂。")
bullet(doc, "加香：掺入 1~3% 香水/精油（见分册三），或干花瓣粉（桂花、玫瑰、茉莉）。")
bullet(doc, "调色：栀子（黄）、苏木（红棕）、姜黄（黄）、青黛（蓝绿，少量）。入模前拌入。")
h2(doc, "三个可直接抄的配方")
