h1(doc, "八、风险与红线")
bullet(doc, "**甲醇**：见 §五，本册第一条红线。掐头、弃霉烂原料、不喝刺鼻酒。")
bullet(doc, "**二氧化碳窒息**：发酵持续放出二氧化碳，会沉积在低处。"
            "酒坊、地窖必须通风；进入长期密闭的发酵空间前，先用灯火试探——火灭即不可进。")
bullet(doc, "**火灾**：酒精蒸气遇明火即燃。蒸馏现场严禁火种，且蒸馏本身要用火——"
            "所以灶与接酒口必须分隔，现场备沙土与水。")
bullet(doc, "**铅中毒**：蒸馏器与容器不可用含铅焊料、铅锡合金部件或劣质金属，"
            "酒液会溶出铅造成慢性中毒。传统做法中铅锡器具是已知的历史教训。")
bullet(doc, "**霉变毒素**：见 §二。制曲与储粮环节一旦发现霉变，整批弃用。")
bullet(doc, "【官府风险】酒在很多朝代都属管制物资：历史上多次实行酒类专卖（榷酒）与禁酒令，"
            "歉年禁酒更是常见。开酒坊前务必查清当地法度（与册 21 联动）。")
note(doc, "本册不给任何配比、温度数值的下限保证与产量估算：曲的活性、米的品种、水质、"
          "季节四项任一变化都会改变结果。请以“出汁、起泡、转辣、澄清”这些可观察判据为准，"
          "每批记录，连续三批稳定后再扩大。")

