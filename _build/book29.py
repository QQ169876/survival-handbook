h1(doc, "一、原理：糖化与发酵是两件事")
bullet(doc, "【科学】酿酒只有两步：先把淀粉切成糖（糖化），再把糖变成酒精（发酵）。")
bullet(doc, "谷物（米、麦、黍、高粱）是淀粉，酵母吃不了淀粉，必须先糖化；"
            "葡萄、梨、枣、蜂蜜本身是糖，可以直接发酵——这就是果酒比粮食酒好做的根本原因。")
bullet(doc, "【科学】发酵是酵母在无氧条件下把糖分解为酒精与二氧化碳，同时放热。"
            "所以发酵缸会冒气泡、会发热，且**会持续放出二氧化碳**。")
bullet(doc, "【判据】糖化是否成功，看有没有甜味与汁液；发酵是否成功，看有没有气泡与酒味。"
            "这两个判据比任何配方都重要。")

h1(doc, "二、酒曲：中国这条路的立身之本")
h2(doc, "① 为什么必须有曲")
bullet(doc, "【史实】以曲蘖酿酒是中国独创的技术路线：用培养好的霉菌与酵母混合制剂（曲）"
            "同时完成糖化与发酵，与西方用麦芽糖化、再加酵母是同一原理的两条独立发明。")
bullet(doc, "【史实】北魏贾思勰《齐民要术》中已系统记载制曲与酿酒的方法，"
            "是世界上最早的酿造学文献之一，其中的许多原则至今成立。")
bullet(doc, "【科学】曲里有两类主角：霉菌负责把淀粉切成糖，酵母负责把糖变成酒精。"
            "所谓“制曲”，本质上是在固体基质上养出一批优势菌群。")

