h2(doc, "① 备料")
bullet(doc, "米（糯米出酒最醇）、黍、粟、高粱、麦皆可；陈米比新米好，新米水分大易酸败。")
bullet(doc, "浸米：泡到米粒能掐断即可，中途换水去酸；浸泡水本身会变酸，这是正常现象但也有限度。")
bullet(doc, "蒸饭：蒸到熟而不烂、内无生心。夹生会带进杂菌，过烂则后期压榨困难。")

h2(doc, "② 摊凉与落缸")
bullet(doc, "【经验】摊凉到“手摸不烫”再拌曲。太烫会把曲里的菌烫死，太凉则迟迟不起酵——"
            "这是新手最常见的两个失败点。")
bullet(doc, "拌曲要匀。曲块先碾碎，分次撒入并翻拌；拌不匀会出现局部酸败。")
bullet(doc, "落缸后中间常扒一个“窝”（搭窝），便于观察出汁与升温——这是传统做法，也是最好的判据窗口。")

h2(doc, "③ 发酵管理")
bullet(doc, "【经验】发酵温度以“温暖不烫手”为宜（约三十度上下）。温度过高易酸败并产生怪味，"
            "过低则发酵停滞。")
bullet(doc, "发酵初期需少量空气供酵母增殖，之后转为厌氧主发酵——所以缸口通常是半封状态。")
bullet(doc, "【判据】正常进程：出汁 → 起泡 → 气泡渐多 → 醅上浮 → 气泡转少 → 醅下沉、酒液澄清。"
            "尝之由甜转辣、甜尽即为终点。")
bullet(doc, "【经验】甜味未尽就压榨，酒会在坛里继续发酵而变酸；等过头则容易被醋酸菌夺走变成醋。")

h2(doc, "④ 压榨、澄清与煎酒")
bullet(doc, "压榨：酒醅装入布袋压榨或用槽榨出酒液。压出的糟就是酒糟（见 §七）。")
bullet(doc, "澄清：静置数日让细渣沉降，取上清液。急不得，澄不清的酒容易继续变酸。")
bullet(doc, "【史实·关键】煎酒：把酒液隔水加热到接近沸点后趁热装坛密封，是中国黄酒能长期存放的关键工序。"
            "这一步杀掉残余微生物与酶，等于给酒“定格”。")
bullet(doc, "【经验】煎酒温度以冒小汽、酒面泛起细密泡沫为准，不可大沸——大沸会把酒精赶跑。")
bullet(doc, "存储：陶坛装盛，密封后置于阴凉处。陶坛微透气，利于老熟；金属与塑料容器在古代不可得或不合适。")

h1(doc, "四、果酒与蜜酒（最容易起步）")
bullet(doc, "葡萄、梨、枣、山楂、猕猴桃一类含糖果实，破碎后直接发酵即可，省掉糖化这一整步。")
bullet(doc, "野生酵母足够：果皮表面自带酵母，破碎后静置常能自然起酵——这是最古老的葡萄酒做法。")
bullet(doc, "蜂蜜酒：蜂蜜稀释后发酵，不需糖化，风味好且耐存放；缺点是蜂蜜本身来之不易（册 07 无关，另寻蜜源）。")
bullet(doc, "【经验】果酒最大的敌人是杂菌与醋酸菌：容器必须洁净，发酵时隔绝空气但能排气，"
            "完成后尽快分离酒液与果渣。")
bullet(doc, "【判据】果酒发酵温度比粮食酒偏低更稳；一旦表面长出白色膜状物（酒花菌一类），"
            "说明已开始变酸，须立刻分离并处理。")

h1(doc, "五、蒸馏：把酒度提上去")
figure(doc, os.path.join(IMG, "46_蒸馏器与掐头去尾.png"), "图46  蒸馏器结构与掐头去尾（酒度与安全的核心）")

h2(doc, "① 装置")
bullet(doc, "【科学】酒精沸点约 78.3℃，水 100℃。加热酒醅时酒精先气化，"
            "把蒸气冷凝下来就得到高酒精度的液体——这就是全部原理。")
bullet(doc, "【史实】中国传统蒸馏器为甑桶加“天锅”的结构：底锅加热酒醅，"
            "蒸气上升遇上方盛冷水的天锅凝结，沿导流槽流出。天锅水须不断更换以保持冷凝效果。")
bullet(doc, "【史实】出土实物中有金代铜制烧酒锅一类器物，说明此类装置在宋金时期已实际使用；"
            "至于蒸馏酒在中国起源的确切年代，学界仍有争议（有东汉、唐、宋、元诸说）。"
            "李时珍《本草纲目》称“烧酒非古法也，自元时始创其法”，是文献中常见的一条记载，"
            "但不宜当作定论——**本册只取“蒸馏装置与掐头去尾的做法”这一层，不参与年代之争**。")
bullet(doc, "装置要点：醅层要松透，让蒸气均匀穿过；接口要密封但不能密闭成压力容器；"
            "冷凝面要够大、冷却水要够冷。")

h2(doc, "② 掐头去尾：本册最重要的一条规矩")
bullet(doc, "【科学】先出来的酒头富集低沸点物质，其中含甲醇与醛类，刺激性最强；"
            "中段（酒心）酒度最高、杂味最少；后段（酒尾）酒度下降，杂醇油一类高沸点物升高。")
bullet(doc, "【科学】甲醇主要来自果胶的分解，所以**薯类、水果皮渣、腐烂果实**作为原料时，"
            "甲醇风险显著高于粮食。")
bullet(doc, "做法：分段接酒，酒头单独收集弃去（或仅作外用燃料），酒心留作饮用，"
            "酒尾单独收集可回醅复蒸，不直接入口。")
note(doc, "甲醇中毒可致失明乃至死亡，且中毒剂量个体差异大。"
          "这是自酿酒最严重的现实风险，没有之一。\n"
          "本册不提供任何“去除甲醇”的土法偏方——正确做法只有：掐掉酒头、原料不用霉烂与高果胶材料、"
          "不喝来路不明或气味刺鼻的酒。")

h2(doc, "③ 判酒度（没有酒度计时）")
bullet(doc, "看酒花：摇动酒液观察泡沫，花大且迅速消散者酒度高，花细密持久者酒度低。"
            "【史实】“看花摘酒”是传统蒸馏工匠的核心手艺。")
bullet(doc, "火试：取少量点燃，能稳定燃烧并基本烧干者酒度已高；点不着或烧一半灭了则酒度低。")
bullet(doc, "【经验】两者都是相对判据，必须用你已知酒度的酒自行标定后才能当尺子用。")
bullet(doc, "【常数】与册 28 同理：常压蒸馏无法越过乙醇-水共沸上限（约 95.6%），"
            "指望反复蒸馏得到纯酒精是不成立的。")

h2(doc, "④ 复蒸与调配")
bullet(doc, "复蒸：把低度酒或酒尾回入醅中再蒸一次，可显著提高酒度与纯净度，代价是燃料。")
bullet(doc, "调配：不同批次兑匀再存放，口感与酒度更稳定。这是酒坊的日常操作。")
bullet(doc, "陈化：蒸馏酒入陶坛存放，酯类生成使辛辣感下降、香气上升；"
            "存放时间以月计，越长越柔。")

