h2(doc, "灭菌与装料")
bullet(doc, "容器：浅陶盘、粗瓷碗、玻璃罐头瓶均可，忌油腻——煮沸后用开水冲三遍。")
bullet(doc, "装料深度不超过 2~3 厘米（表面培养法的关键：青霉是需氧菌，液面越大、越浅，产量越高）。")
bullet(doc, "加盖蒸煮 40~60 分钟灭菌，趁热移入干净处晾至室温，盖清洁湿布备用。")

h1(doc, "四、接种与培养")
bullet(doc, "接种：用干净竹签挑一小块带孢子的霉（青绿色部分），点在培养液表面中央，几点分散更稳。")
bullet(doc, "环境：25~27℃ 最适宜（夏秋室温即可；冬天放灶台附近，摸着'温而不烫'的位置）。")
bullet(doc, "避光静置，不要搅动。盖子留缝透气（需氧！），防虫防尘用纱布罩。")
bullet(doc, "第 1~2 天出现白色绒毛 → 第 3~5 天转青绿色 → 第 5~7 天菌膜成熟，此时培养液淡黄微浑、"
            "闻起来有轻微霉香和酸味——这就是含青霉素的发酵液，立即收获（放久了霉素会被菌自己分解）。")

h1(doc, "五、提取与浓缩：五个步骤做出粗制品")
para(doc, "现代工业用乙酸乙酯萃取、冷冻干燥，我们做不了；土法路线走'过滤—酸化—炭吸—洗脱—浓缩'，"
          "得到的是黄棕色粗膏，效价约为工业品的几十分之一，但外用对付伤口感染足够。")
figure(doc, os.path.join(IMG, "02_过滤装置.png"), "图 1-2  过滤与吸附装置")
h2(doc, "第 1 步：过滤除菌体")
para(doc, "发酵液先静置半小时，取上层清液，缓缓倒入'布—砂—炭—布'的滤层（见图 1-2），滤液澄明即可。"
          "滤纸没有就用细麻布叠四层，垫上洗净焙干的细砂与碎木炭。")
h2(doc, "第 2 步：酸化")
para(doc, "青霉素在 pH 2.5~3 时最容易被活性炭吸住（此时它呈酸分子状态）。用米醋（或酸果汁）逐滴加入滤液，"
          "边加边尝——以'明显发酸但不刺喉'为度，没试纸就靠经验：一滴入奶，能使其凝结的酸度即过强。")
h2(doc, "第 3 步：活性炭吸附")
para(doc, "焙干的硬木炭研碎，按每升滤液加 30~50 克投入，搅拌 10 分钟，静置 1 小时，再过滤弃液、留住湿炭。")
h2(doc, "第 4 步：碱液洗脱")
para(doc, "用微碱水（草木灰淋滤液煮沸放凉后加水稀释至'舌尝微涩不蚀'）100 毫升，分三次浇洗湿炭，收集洗脱液——"
          "青霉素在碱性下脱附回到水里。此时液体从无色转为淡黄棕色。")
h2(doc, "第 5 步：低温浓缩与干燥")
para(doc, "水浴（锅隔水）40~50℃ 缓缓蒸浓至膏状，忌超过 60℃、忌直火、忌阳光。摊在净瓷片上薄薄一层，"
          "阴干后刮下，即为土制青霉素干粉。装干净小瓷瓶，蜡封口，避光存放。")
note(doc, "产率：本手册不给出具体产率数字——土法培养的产率受菌种、温度、培养基、提取损失影响极大，"
          "任何'每平方米能出几克'的说法都不可靠。请按第六节的平板法实测你的制品效价，以实测为准。"
          "唯一可以确定的是：产量很低，且批次之间差异很大，不要按固定剂量用药。", color=(20, 90, 40))

h1(doc, "六、效价检测：知道你的药'有多灵'")
para(doc, "做一批'细菌平板'：土豆煮熟压泥 + 米汤熬稠 + 明胶（皮胶/鱼胶）10% 凝固成板，"
          "表面涂抹一点新鲜脓液（含细菌），保温一夜让细菌长开。")
bullet(doc, "在平板上放一枚蘸了你的青霉素液的纸片/棉线环，24 小时后周围出现透明'抑菌圈'——有效。")
bullet(doc, "圈越大越透，效价越高；没有圈 = 这批失败，从头找原因。")
bullet(doc, "这个平板法也可用于'菌种初筛'：把不同来源的霉各点一点，谁的圈大用谁做种。")

h1(doc, "七、怎么用（最重要的一节）")
h2(doc, "外用（首选，最安全）")
bullet(doc, "伤口：清创排脓后，用粗制品溶液（干粉 1 克兑凉开水 20 毫升）冲洗、湿敷，纱布覆盖，每日换药。")
bullet(doc, "脓肿：切开引流后腔内撒干粉少许。")
bullet(doc, "眼/耳感染：极稀溶液（1:100）点洗。")
h2(doc, "口服（次选）")
para(doc, "现实提醒：土制品的效价未知且批次差异极大，因此不存在可靠的'标准剂量'。"
          "历史上青霉素口服的确被使用过（且口服吸收差、受胃酸破坏），但在没有效价测定的条件下，"
          "任何具体克数都只是猜测。若确需口服，原则是从极小量开始、观察反应、优先外用，"
          "并且必须先做过敏试验。把口服当作'最后手段'而不是常规选项。")
h2(doc, "过敏试验（用药前必做）")
bullet(doc, "取极稀溶液（1:1000，即干粉 1 毫克兑 1 毫升水）一滴，涂在前臂划痕处或点入眼角。")
bullet(doc, "15 分钟内出现红肿、痒、风团 → 过敏，此药对该人禁用。")
bullet(doc, "首次用药的人必须试；换批次也要重试（杂质不同，反应不同）。")
note(doc, "绝对禁止：不作皮试直接口服大剂量、把粗制品用于注射。青霉素过敏性休克发生极快，古代条件下无解。")

h1(doc, "八、保存与失效")
bullet(doc, "干粉比水溶液耐存：蜡封小瓶、避光、阴凉（井窖最理想），可存 1~3 个月，效价逐月下降。")
bullet(doc, "水溶液当天有效，最多两天——现配现用。")
bullet(doc, "遇热（>60℃）、遇强酸强碱、遇阳光都会迅速失效。")
bullet(doc, "每批新制品用平板法复测一次效价再投入使用。")

