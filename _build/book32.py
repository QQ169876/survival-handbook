h2(doc, "② 搭法")
bullet(doc, "隔地：先铺厚厚一层干草、树叶或树枝，把身体与地面隔开——地面导热极快。")
bullet(doc, "挡风：出入口背对风向，用树枝与土垒出挡风墙。")
bullet(doc, "保暖：外层覆盖厚枝叶并填实缝隙，宁可小一点，不要大而漏风。")
bullet(doc, "A 字棚、斜靠棚、雪洞（寒冷地区）是最省力的三种形式，按材料与天气选。")
h2(doc, "③ 失温与中暑")
bullet(doc, "失温（低温 + 湿 + 风）：早期剧烈颤抖、口齿不清、动作笨拙。"
            "处置：换干衣、饮热糖水、避风、贴身取暖，禁止饮酒。")
bullet(doc, "中暑（高温 + 暴晒）：皮肤灼热却不出汗、头痛恶心、意识模糊。"
            "处置：移到阴凉处、降温、补含盐水。")
bullet(doc, "【判据】颤抖停止、意识模糊是失温加重的信号，不是好转——必须立刻 warming 并求救。")

