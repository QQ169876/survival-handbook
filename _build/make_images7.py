def img_sugar():
    im, d = new(1000, 620, "图7-2  甘蔗制糖全流程（从榨汁到白糖）")
    steps = [("① 收割榨汁", "石碾/木辊双辊\n压榨2~3遍"),
             ("② 加灰澄清", "石灰乳中和\n煮沸撇沫"),
             ("③ 过滤", "麻布滤去渣滓\n得清汁"),
             ("④ 连环锅熬煮", "由稀到浓依次\n过锅，撇沫"),
             ("⑤ 打砂结晶", "糖膏入糖床\n搅拌冷却"),
             ("⑥ 分蜜脱色", "糖漏+黄泥水淋\n上层变白"),
             ("⑦ 干燥成品", "晒/焙干\n分级装缸")]
    x0, y0, bw, bh, gap = 35, 90, 118, 96, 14
    for i, (t, s) in enumerate(steps):
        col = i % 4
        row = i // 4
        x = x0 + col * (bw + gap)
        y = y0 + row * (bh + 80)
        box(d, x, y, bw, bh, t + "\n" + s, fill=(250, 242, 225), outline=(150, 90, 30), fs=14)
        if col < 3:
            arrow(d, (x + bw + 2, y + bh / 2), (x + bw + gap - 2, y + bh / 2), color=(150, 90, 30))
        if row == 0 and col == 3:
            arrow(d, (x0 + bw / 2, y + bh + 4), (x0 + bw / 2, y + bh + 56))
            label(d, x0 + bw / 2 + 12, y + bh + 20, "转入熬制阶段", fs=14, color=(120, 80, 30))
    label(d, 40, 300, "榨辊：硬木双辊（或石碾），畜力牵引；蔗渣复水再榨一次可多出 10~15% 糖分", fs=15)
    label(d, 40, 328, "石灰量：每百斤蔗汁加石灰 0.3~0.6 斤（先化乳再兑），过量会把蔗糖分解成不能结晶的转化糖", fs=15, color=(170, 40, 40))
    label(d, 40, 356, "火候：糖浆沸点到 116~118℃（滴水成珠、拉丝不断）即起锅；过火则焦苦发黑", fs=15)
    label(d, 40, 384, "打砂：糖膏起锅后入浅盆快速搅拌散热，搅出细晶即为红糖/黑糖（含蜜）", fs=15)

    # 糖漏
    label(d, 560, 300, "糖漏·黄泥水淋脱色法（白糖的古法）", fs=18, color=(150, 60, 20))
    d.polygon([(600, 360), (820, 360), (720, 520), (680, 520)], fill=(240, 230, 210), outline=(90, 60, 30), width=3)
    label(d, 640, 380, "装入褐色糖膏", fs=14)
    d.rectangle([(600, 330), (820, 358)], fill=(215, 195, 130), outline=(120, 90, 40), width=2)
    label(d, 640, 338, "顶部覆湿黄泥浆（厚3~5cm）", fs=14)
    d.ellipse([(694, 520), (706, 535)], fill=(80, 60, 40))
    label(d, 715, 522, "底孔滴出糖蜜（收集）", fs=14)
    d.polygon([(660, 540), (740, 540), (730, 585), (670, 585)], fill=(250, 248, 240), outline=(120, 120, 120), width=2)
    label(d, 672, 556, "接蜜缸", fs=14)
    label(d, 850, 380, "水慢慢下渗\n溶解带走糖蜜\n与色素", fs=14)
    label(d, 560, 590, "约 7~15 天后：上层雪白（白糖），下层仍黄褐（红糖），切开分层取用", fs=15, color=(30, 100, 60))
    save(im, "11_制糖流程.png")


