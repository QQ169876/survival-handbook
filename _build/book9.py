h2(doc, "① 选址")
bullet(doc, "高燥背阴：屋后北侧、土坡背阴面、树荫下。绝不选低洼积水处。")
bullet(doc, "地下水位要低于窖底 1 米以上；雨季四周挖排水沟引走地表水。")
bullet(doc, "黏土层最好（易成型、隔水）；沙土需夯筑或砖石砌护。")
h2(doc, "② 窖体结构")
bullet(doc, "深度 3~5 米，越深越恒温（地下 3 米以下全年约 10~15℃）。")
bullet(doc, "形状：口小底大的袋状或直筒方形，减少空气对流。")
bullet(doc, "底部：碎石/卵石渗水层 20~30 cm，融水能及时渗走并由暗沟引出——积水是冰窖的头号杀手。")
bullet(doc, "顶部：木梁/石板承重 + 草苫 + 覆土 30 cm 以上，彻底遮光。设可封闭的通气孔。")
bullet(doc, "门：朝北或背阴，做成双层木门（中间填草），斜坡或阶梯进出，随开随关。")
h2(doc, "③ 采冰")
bullet(doc, "时机：冬至后最冷时段，冰层厚达 15~20 cm 以上时（要能承重）。")
bullet(doc, "水面：优先洁净的活水湖、河湾上游段；污水坑的冰只用于冷却，不作食用。")
bullet(doc, "工具：冰镩（铁锥）、冰锯（带齿长刀）、木钩与撬杠，绳索拖运。")
bullet(doc, "规格：切成 40~60 cm 见方的大块——块越大，表面积比越小，越耐存。")
h2(doc, "④ 入窖与存冰")
bullet(doc, "一次性装满，块与块紧贴，缝隙用碎冰和雪填实（雪是免费的隔热补充）。")
bullet(doc, "每层冰块之间铺 5~10 cm 稻草隔开，防止冻成一坨难以取用。")
bullet(doc, "四周与顶部覆盖稻草/麦秸/谷糠/锯末 40~80 cm，压实。")
bullet(doc, "取冰只在清晨或傍晚，取完立即回填隔热层、封门。")
h2(doc, "⑤ 损耗控制")
bullet(doc, "北方（黄河以北）管理得当可存到盛夏，损耗 30% 左右；管理差则超过 60%。")
bullet(doc, "南方无天然冰的季节只能靠化学制冷；或者高海拔山区找天然冰洞。")
bullet(doc, "减损三招：块要大、隔热要厚、门要少开。")

h1(doc, "三、全年方案：硝石制冷")
para(doc, "硝酸钾（硝石）溶于水时会大量吸热，能让溶液温度骤降到 -10℃ 以下。"
          "这是中国古代确有记载的制冰法，也是你唯一能'夏天随时造冰'的手段。")
figure(doc, os.path.join(IMG, "16_硝石制冰.png"), "图 9-2  双层罐制冰装置与硝石土法获取")
h2(doc, "① 制冰操作")
bullet(doc, "装置：大木盆或陶盆（外桶）装冷水，中间放一只小陶罐（内罐），内罐装清水并用蜡或湿布严密封口。")
bullet(doc, "配比：水 100 份，硝石 100~140 份。分 3~4 次投入，边投边用木棒搅拌加速溶解。")
bullet(doc, "效果：外桶溶液降到 -10~-20℃，内罐清水 10~30 分钟即可结冰。")
bullet(doc, "保温：外桶再裹一层麻布或棉被，减少外界热量进入，出冰更快。")
bullet(doc, "取出：砸开内罐冰壳，冰取出后用清水冲洗外壁，再用于食物或医疗。")
note(doc, "内罐必须密封！硝石溶液渗入就不能食用。取出的冰外壁必须清水冲净再接触食物。")
h2(doc, "② 硝石从哪来")
bullet(doc, "找硝土：老墙根、厕所/畜圈墙脚、地窖壁、猪圈牛栏地面泛出的白色絮状霜——这是硝酸盐随水分迁移到表面结晶的结果。")
bullet(doc, "判断：取一点撒在炭火上，噼啪助燃的即含硝；尝之凉而微苦（少量无害，别多尝）。")
bullet(doc, "浸提：硝土装入底部铺草的木桶，浇清水淋下，接住流出的硝水（淋硝），稀水回浇提浓。")
bullet(doc, "转化：硝水加草木灰浸出液（碳酸钾），把钙、镁硝酸盐转成碳酸盐沉淀，滤去——这一步决定结晶纯度。")
bullet(doc, "熬煮结晶：清液熬到液面起晶膜，冷却析出粗硝石；重溶再结晶 2 次即为精硝石。")
h2(doc, "③ 回收复用（成本关键）")
bullet(doc, "制冰后的硝石溶液不要倒掉：过滤后重新熬煮浓缩、冷却结晶，硝石可反复使用，损耗主要在机械夹带。")
bullet(doc, "把'制冰—回收'做成闭环，硝石就从消耗品变成固定资产，夏天也能持续出冰。")
bullet(doc, "副产价值：硝石同时是火药的氧化剂来源，一物两用（详见火药分册）。")
h2(doc, "④ 局限")
bullet(doc, "产量低：每 1 份硝石约冻出 0.3~0.5 份冰，一次几斤到十几斤，做不了大宗冷藏。")
bullet(doc, "定位正确：它是'做食用冰、制冰饮、给药品降温'的手段，不是替代冰窖的方案。")

h1(doc, "四、零消耗辅助：蒸发冷却与夜间辐射")
figure(doc, os.path.join(IMG, "17_蒸发冷却与夜间结冰.png"), "图 9-3  陶罐冰箱、湿布风冷与夜间辐射结冰")
h2(doc, "① 陶罐冰箱（蒸发冷却）")
bullet(doc, "结构：一只未上釉的粗陶大罐，内套小罐，夹层填湿沙或湿木屑，罐口盖湿布。")
bullet(doc, "原理：水从多孔陶壁渗出蒸发，带走热量。干燥地区内温可比环境低 10~15℃。")
bullet(doc, "条件：必须空气干燥且通风；南方梅雨季几乎无效（水汽已饱和）。")
h2(doc, "② 湿布风冷")
bullet(doc, "任何陶瓮外壁裹多层湿麻布，布下端浸在接水盘里靠毛细作用续水，置于过道风口或风塔下。")
bullet(doc, "配合白天封窗避热、夜间开窗取冷，能把室内物品温度压低数度。")
h2(doc, "③ 夜间辐射结冰")
bullet(doc, "原理：晴朗无云的夜晚，物体以红外线向天空辐射散热，可降到气温以下数度。")
bullet(doc, "做法：把浅陶盘（水深不超过 2 cm）放在厚干草或秸秆隔热层上，摆在开阔、无风、远离屋檐树荫的地面。")
bullet(doc, "收获：凌晨 3~5 点气温最低时收集薄冰，趁冷集中送入冰窖。")
bullet(doc, "局限：只在干燥少云地区（中亚、西北、高原）效果明显，产量很小，是补充而非主力。")

h1(doc, "五、机械制冷：为什么不推荐")
bullet(doc, "压缩式制冷需要：精密加工的压缩机、耐压密封系统、合适的制冷剂、电机驱动。任何一环在古代都无法自给。")
bullet(doc, "吸收式（氨-水）制冷虽然不需要电，但需要高纯度氨、耐腐蚀承压容器与严格的密封，同样不可行。")
bullet(doc, "结论：除非你随身带着现代冰箱或压缩机，否则不要在这条路上投入资源。把精力放在冰窖和硝石上。")
note(doc, "唯一值得尝试的'半机械'：利用分册六的水力/畜力带动风箱吹风，强化蒸发冷却——收益有限，成本却高，属于锦上添花。")

h1(doc, "六、冰的用途细则")
h2(doc, "食物保鲜")
bullet(doc, "鱼肉禽类：冰块不直接接触食物（用陶盆隔开），融水及时排走，可延长保鲜 2~5 天。")
bullet(doc, "乳品与油脂：低温延缓酸败，夏季尤其明显。")
bullet(doc, "盐渍 + 冷藏叠加效果最好（见分册七）。")
h2(doc, "医疗")
bullet(doc, "高热降温：冰袋敷大血管处（颈侧、腋下、腹股沟），注意用布隔开防冻伤，每次不超过 20 分钟。")
bullet(doc, "外伤：冷敷消肿止痛，减少出血；配合分册一的青霉素使用效果更好。")
bullet(doc, "局部麻醉：长时间冷敷可使局部感觉迟钝，便于处理小伤口或拔牙。")
bullet(doc, "药品保存：青霉素溶液、血清类在低温下活性保持更久（注意仍不能久存，且不可冻结生物制品）。")
h2(doc, "生意")
bullet(doc, "冰饮：冰镇酸梅汤、果汁、凉茶，夏季街边暴利。")
bullet(doc, "冰酪/酥山：奶油或奶浆加蜜与果泥，冰镇半凝，是唐代就有的高档甜品。")
bullet(doc, "冷食保存：给酒楼、鱼贩、肉铺供冰，按日收费，是稳定现金流。")

h1(doc, "七、安全与常见坑")
bullet(doc, "冰窖窒息与坍塌：深窖作业前先通风（用风箱或扇子），窖内缺氧可致命；顶部覆土要夯实并设支撑，雨季防塌方。")
bullet(doc, "采冰溺水：冰层厚度不足 15 cm 不上人；多人作业时绳索互保，凿开的冰窟要标记。")
bullet(doc, "食用冰卫生：取自污水河的冰只可用于冷却（外壁接触），食用冰必须用洁净水在小罐内冻制。")
bullet(doc, "硝石毒性：硝酸钾低毒但浓溶液与粉尘刺激黏膜；制冰内罐必须密封，冰取出后清水冲净；严禁把硝石直接加入饮用水。")
bullet(doc, "冻伤：冰袋直接接触皮肤超过 20 分钟会造成冻伤，务必用布包裹并定时移开。")
bullet(doc, "融水处理：冰窖底部排水不畅会泡烂隔热层，导致整窖快速融化——排水是日常巡检第一项。")
bullet(doc, "火药风险提示：硝石是火药原料，大量囤积可能引来官府注意，储存要低调、分散，与木炭硫磺分开存放。")

h1(doc, "八、推荐实施顺序")
para(doc, "第一年冬季（落地后最重要的一件事）：选高燥背阴处挖冰窖，深 3~5 米，做好排水与隔热；"
          "最冷时段采大块冰一次性装满，记录取用与损耗，摸清本地能存到几月。"
          "第一年春季：同步收集老墙硝土，试淋硝、熬硝，跑通硝石制冰与回收闭环，产出第一批'夏天也能做的冰'。"
          "第一年夏季：冰饮摊与酒楼供冰双线试水，用冰为青霉素溶液与外伤冷敷提供保障。"
          "第二年：按损耗数据扩建冰窖（或做双窖轮换），干燥地区加建陶罐冰箱与夜间结冰场，形成全年供冰体系。", indent=False)

