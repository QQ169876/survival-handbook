    plants = [("除虫菊", "含除虫菊酯\n天然杀虫剂之王", (250, 245, 225)),
              ("苦楝/川楝", "川楝素\n广谱忌避，有毒勿内服", (245, 240, 225)),
              ("烟草", "尼古丁杀虫\n浸水喷洒", (240, 235, 220)),
              ("香茅/柠檬草", "香茅醛\n涂抹驱蚊", (235, 250, 235)),
              ("薄荷/留兰香", "薄荷脑\n清凉驱避", (235, 250, 245)),
              ("艾草/蒿", "烟熏最佳\n全境常见", (240, 248, 235)),
              ("菖蒲/白芷/苍术", "香囊避疫\n佩挂驱虫", (245, 245, 235)),
              ("青蒿", "揉汁涂肤\n兼退虚热", (240, 248, 240))]
