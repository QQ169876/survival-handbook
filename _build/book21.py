bullet(doc, "第三步：查**水与粮**。水源是否洁净、粮价是否平稳、去年有没有歉收。")
bullet(doc, "第四步：查**官府距离**。离县城多远、衙门管不管事、里正/保甲是怎么运作的。")
bullet(doc, "第五步：查**产业基础**。有没有铁匠铺、瓦窑、酒坊、纸坊——这决定你手册里的技术能落地几成。")
bullet(doc, "第六步：如果前五项都还过得去，**原地不动是最优解**。迁徙是古代风险最高的行为之一。")
