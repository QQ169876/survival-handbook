h1(doc, "十二、安全总则")
bullet(doc, "稀释浓硫酸只能把酸缓缓加入水中，绝不可反向——反向会因局部沸腾而喷溅。")
bullet(doc, "任何气体吸收装置都必须防倒吸：管口贴水面、或加装缓冲瓶。")
bullet(doc, "酸性气路与碱性气路（氨）不要共用同一套装置残留，中和反应会在管道里生成固体堵塞。")
bullet(doc, "所有试剂必须标注并单独存放，尤其不能与食物、药材混放。历史上误服强酸的案例极多。")
bullet(doc, "废料处理：酸性废液用石灰或草木灰中和后再倾倒；重金属废液（含铜、铅）单独收集深埋。")
bullet(doc, "【本册底线】涉及汞的操作一律不写；涉及氟化物、氰化物、放射性矿物的一律不写。"
            "这三类在古代没有安全处理的可能。")

h1(doc, "十三、实施顺序建议")
