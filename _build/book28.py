h1(doc, "十一、通用装置：这几件必须先备齐")
bullet(doc, "耐酸容器：上釉陶器、玻璃器皿（册 27）、铅衬木桶（铅有毒，仅限非食用用途）。普通陶罐会被酸渗透。")
bullet(doc, "冷凝与吸收：复用册 03 的蒸馏冷凝装置；吸收瓶须留排气口，绝不可做成密闭系统。")
