h1(doc, "二、总原则")
bullet(doc, "先硫酸，后一切。三酸之中硫酸是“钥匙”：有了它，盐酸与硝酸各只需一步蒸馏。"
            "所以第一条要攻的产线是干馏绿矾制硫酸。")
bullet(doc, "试剂不是越纯越好，而是“够用即可”。为提纯花掉的燃料往往超过它带来的收益。")
bullet(doc, "每一步都要有可判别的终点判据（沉淀是否继续生成、气体是否还放出、结晶是否析出），"
            "没有判据的工序等于闭眼操作。")
bullet(doc, "【判据】本册一律不给配方比例与收率。矿石品位、燃料温度、器皿材质三项在各地差别极大，"
            "照抄数字没有意义；给的是反应原理、装置结构、终点判据与危险点。")

h1(doc, "三、石灰与碱系统")
h2(doc, "① 石灰")
bullet(doc, "【科学】石灰石（碳酸钙）强热分解出生石灰（氧化钙）并放出二氧化碳，"
            "此反应需在约 900℃ 以上才能充分进行，与册 04 的石灰窑是同一件事。")
bullet(doc, "判断烧透：出窑的生石灰块应轻、敲击声脆、遇水迅速放热崩解；"
            "中间夹生的石块（未烧透的石心）必须拣出重烧。")
bullet(doc, "消化：生石灰加水剧烈放热，变成熟石灰（氢氧化钙）。必须少量多次加水并搅拌，"
            "局部过热会把水汽炸开伤人。")
bullet(doc, "石灰水：熟石灰在水中溶解度很小，取上层清液即得饱和石灰水——"
            "这是最便宜的碱，也是检验二氧化碳的试剂（通入后变浑浊）。")

h2(doc, "② 草木灰与碳酸钾")
bullet(doc, "草木灰主要成分是碳酸钾，硬木灰含量高于稻草灰。淋滤、浓缩、熬干可得粗钾碱（册 02 已述）。")
bullet(doc, "【判据】浓缩终点用鸡蛋浮沉法判断（露出约硬币大小即可）。这是古代通用的密度判据，"
            "与册 07 试卤同源。")

h2(doc, "③ 苛化制氢氧化钾")
bullet(doc, "【科学】碳酸钾溶液与石灰乳共煮，生成碳酸钙沉淀与氢氧化钾溶液："
            "沉淀不断生成、上层清液不再与石灰水反应生成新沉淀，即为反应接近终点。")
bullet(doc, "取上层清液即得氢氧化钾溶液——这是肥皂（册 02）真正需要的强碱。")
bullet(doc, "【经验】清液必须澄清，混入的碳酸钙会让皂体粗糙；宁可静置久一点。")

h1(doc, "四、硫酸（干馏绿矾法）")
figure(doc, os.path.join(IMG, "44_三酸制备.png"), "图44  三酸的土法制备装置")
bullet(doc, "【科学】绿矾（水合硫酸亚铁）受热先脱去结晶水，继续强热则分解，"
            "放出三氧化硫与二氧化硫，三氧化硫溶于水即得硫酸。")
bullet(doc, "【史实】以干馏绿矾制硫酸的方法在阿拉伯与欧洲炼金术文献中均有记载，"
            "欧洲早期称所得产物为“绿矾油”，是铅室法工业化之前硫酸的主要来源。"
            "此路线在历史上确凿存在，属于本手册少数有明确史料支撑的无机合成路线。")
bullet(doc, "装置：密闭的陶甑或铁釜装料，导气管把气体引入受器，受器内预先放少量水并外部水冷。")
bullet(doc, "关键：整条气路必须尽量短且密封，漏气则产率骤降；受器冷却不足则酸雾逸散，"
            "操作者会立刻被呛到——这既是安全问题，也是产率信号。")
bullet(doc, "浓缩：所得酸液含水较多，须在陶器或玻璃器皿中缓慢蒸发浓缩。"
            "浓缩时会放出大量刺激性酸雾，必须在户外上风向进行。")
bullet(doc, "原料来源：绿矾可由黄铁矿（硫铁矿）风化后水浸、再蒸发结晶得到，"
            "也可从旧矿井的矾水中熬取。")
note(doc, "危险点：二氧化硫与三氧化硫都是强刺激性有毒气体，吸入会灼伤呼吸道并引发痉挛。"
          "整套装置必须在户外、上风向操作，操作者站在来风一侧，一旦闻到刺激性气味立即撤离。"
          "废渣（氧化铁红）其实是有用的颜料（铁红），可留给册 12 与册 23 做印泥与颜料。")

h1(doc, "五、盐酸（食盐 + 硫酸）")
bullet(doc, "【科学】食盐与浓硫酸共热放出氯化氢气体；氯化氢极易溶于水，"
            "把气体导入水中吸收即得盐酸。")
bullet(doc, "装置要点：导气管口只能贴近水面、绝不可插入水中。"
            "氯化氢溶解极快，一旦插入会形成负压把水倒吸回反应釜，引发喷溅甚至炸裂。")
bullet(doc, "温和加热时生成硫酸氢钠并放出一分子氯化氢；加强热可进一步反应，"
            "但温度过高会使硫酸分解、产物混杂——古代条件下取前者更稳。")
bullet(doc, "尾气处理：未被吸收的氯化氢须导入石灰水或草木灰水中和，不可直接放空。")
bullet(doc, "副产：残留的硫酸钠（芒硝一类）可作助熔剂与缓泻药，也可供册 27 玻璃配料参考。")

h1(doc, "六、硝酸（硝石 + 硫酸）")
bullet(doc, "【科学】硝石（硝酸钾）与浓硫酸共热蒸馏，硝酸蒸气逸出后冷凝收集，"
            "残留物为硫酸氢钾。")
bullet(doc, "【史实】以硝石配硫酸（或配绿矾、明矾一类）蒸出硝酸的方法，"
            "在欧洲近代早期化学文献中有明确记载，所得液体古称“强水”。")
bullet(doc, "装置：须用玻璃或上釉陶器作蒸馏器，普通陶器会被酸腐蚀渗漏；接口用湿布与黏土密封。")
bullet(doc, "温度控制：温度过高硝酸会分解并放出棕色气体，冷凝液中也会混入杂质。"
            "缓火慢蒸、宁慢勿猛。")
bullet(doc, "用途：册 26 的硝化纤维素路线依赖它；此外硝酸是少数能溶解银的酸，"
            "可用于金银分离与试金（与册 04 联动）。")
note(doc, "硝酸蒸气灼伤呼吸道与皮肤，且能引燃有机物（麻、木、纸）。"
          "蒸馏现场不得存放任何可燃杂物，冷凝液不可用木塞直接封口（会被腐蚀碳化），"
          "须用玻璃塞或磨口、或蜡封于阴凉处。")

h1(doc, "七、氨与铵盐")
bullet(doc, "【史实】人畜尿液在存放发酵过程中会因尿素分解而产生氨与碳酸铵——"
            "古代以陈尿洗衣、以尿液媒染，利用的正是这一点，这是最易得的弱碱来源。")
bullet(doc, "【史实】干馏骨、角、毛发可得含氨的液体（历史上称“鹿角精”一类的氨水），"
            "是欧洲近代早期的氨水来源之一。")
bullet(doc, "富集：把发酵尿或干馏液与石灰共热，可把铵盐中的氨驱出，"
            "导入冷水中吸收即得氨水。")
bullet(doc, "硇砂（氯化铵）：氨与氯化氢两股气体相遇会生成浓白烟，沉积下来即为氯化铵。"
            "【史实】天然硇砂多采自火山升华物与煤自燃处的凝结物，属传统药材与焊药。")
bullet(doc, "用途：染色助剂、清洁去油、焊接前的金属表面处理（氯化铵能去除氧化膜）。")

h1(doc, "八、乙醇、醋酸与溶剂")
h2(doc, "① 乙醇")
bullet(doc, "发酵（与册 20、册 07 同源）后用册 03 的蒸馏装置提浓。")
bullet(doc, "【常数】常压下乙醇与水会形成共沸物，因此单纯反复蒸馏无法越过约 95.6% 的浓度上限——"
            "这是物理常数，不是操作失误。")
bullet(doc, "如需无水乙醇：加足量生石灰回流后重新蒸馏，可得更高浓度的乙醇。"
            "生石灰吸水而不与乙醇反应，这是实验室常规做法。")
bullet(doc, "用途：溶剂（册 03 香水、册 26 虫胶漆）、消毒（册 13）、燃料（灯与炉）。")

h2(doc, "② 醋酸")
bullet(doc, "【科学】酒在醋酸菌作用下被空气氧化成醋，此过程需要氧气，敞口比密封快。")
bullet(doc, "所得食醋浓度有限；浓缩可用冻结法——醋酸在较低温度会先行结晶析出，"
            "把未冻结的稀液倒掉即可提高浓度（冰醋酸之名即由此而来）。")
bullet(doc, "【经验】蒸馏浓缩醋酸腐蚀性较强且易损失，冻结法对器具要求最低，优先采用。")

h2(doc, "③ 有机溶剂")
bullet(doc, "松节油：松脂经蒸馏可得松节油与松香，是中国传统产物；"
            "松节油是古代最实用的非水溶剂，可用于稀释漆与配制油墨（册 23）。")
bullet(doc, "桐油：本身是干性油，加热后成膜，是防水涂料的核心（册 02、册 25 已用）。")
bullet(doc, "【判据】溶剂的选择看三件事：溶不溶、干得快慢、有没有毒。"
            "在通风条件差的工坊里，宁可用慢干的油，也不要用挥发快的溶剂。")

h1(doc, "九、吸附剂与干燥剂")
bullet(doc, "活性炭：木炭经高温水蒸气处理（活化）可显著提高吸附能力，"
            "这是工业上物理活化法的基本原理。活化后的炭要趁热隔绝空气冷却，出炉后密封保存。")
bullet(doc, "【判据】活性炭好坏可用“脱色试验”判定：取一量筒有色液体（如糖蜜稀释液或染色废水），"
            "加入等量待测炭，静置后比色，颜色最浅者最优。")
bullet(doc, "干燥剂：生石灰是最通用的干燥剂（不可用于酸性气体）；"
            "浓硫酸可作气体干燥剂（不可用于碱性气体如氨）。")
bullet(doc, "用途：册 01 青霉素吸附洗脱、册 14 净水过滤、册 08 味精脱色，都依赖活性炭。")

