h1(doc, "四、主线二：虫胶与生漆（中国本土优先）")
bullet(doc, "虫胶：热软化、酒精溶解、冷后硬固。可做成酒精溶液当涂料（绝缘漆、木器罩光），"
            "也可掺木粉/滑石热压成模塑件。")
bullet(doc, "生漆：滤去杂质即可用，在温度适中、湿度较高的环境中固化最快，"
            "阴房（湿房）是漆器工坊的核心设施。")
bullet(doc, "【经验】漆酚会使人过敏起疹，割漆与髹漆须穿长袖、避免皮肤接触，新工常需一段时间适应。")
bullet(doc, "两者都可与布、麻胎结合做成层压件（漆布、漆纸），强度高又轻——"
          "这是古代条件下最接近“复合材料”的东西。")

h1(doc, "五、主线三：酪蛋白塑料（仿象牙的暴利品）")
bullet(doc, "原料：脱脂奶制酪或酸奶沥出的酪蛋白。关键是把水挤干净——含水量决定成型与开裂。")
bullet(doc, "成型：趁湿压入模具，或直接切成坯块待后续车削。")
bullet(doc, "硬化：浸入甲醛水溶液，由表及里逐步硬化。厚件需要很长时间，"
            "这也是酪蛋白塑料件通常做得不厚的原因。")
bullet(doc, "【史实】甲醛由霍夫曼于 1867 年前后确立制备法；本册不给甲醛的土法合成路线——"
            "工业上由甲醇氧化制得，甲醇可通过木材干馏得到，但氧化一步需催化与控温，"
            "家庭条件下收率与安全性都不理想。")
bullet(doc, "后处理：干燥后打磨、染色（与册 12 染料共用），可做纽扣、梳子、刀柄、珠宝仿制品。")
note(doc, "甲醛有强烈刺激性与致癌性，硬化槽必须加盖并置于通风处，操作者避免吸入与皮肤接触。"
          "没有可靠通风条件时，本条路线应直接放弃。")

h1(doc, "六、主线四：赛璐珞（透明塑料片）")
bullet(doc, "路线：棉纤维经硝酸-硫酸混酸硝化 → 反复水洗至中性并煮洗稳定 → 脱水 →"
            "与樟脑在酒精中捏合 → 热压成块 → 切片、打磨。")
bullet(doc, "依赖：硝酸与硫酸（见册 28）、樟脑（樟木蒸馏可得，册 03 蒸馏装置可用）、酒精。")
bullet(doc, "【史实】樟脑长期以樟木蒸馏获取，是中国与日本的传统产物，"
            "这一点使赛璐珞成为穿越条件下少数“原料链可闭合”的合成塑料。")
bullet(doc, "用途：透明片（灯罩、镜片的廉价替代）、梳子、刀柄、乒乓球一类弹性体、胶片基材。")
note(doc, "安全红线：硝化纤维素极易燃，燃烧速度快且难以扑灭；干燥的硝化物受热、受撞击、"
          "长期存放分解都可能自燃。赛璐珞制品在历史上造成过多次重大火灾。\n"
          "本册不写混酸的配比、温度与时程。若你在史料中看到相关数字，那是记载，不是施工参数——"
          "缺少温度控制与分析手段时，硝化反应本身就是最大的危险源。")

h1(doc, "七、成型与加工：通用手艺")
bullet(doc, "模压：木模或陶模加螺旋压杠、楔子加压。模具表面须光滑并涂脱模剂（油、蜡、滑石粉）。")
bullet(doc, "热压：材料软化后趁热加压定型，冷却脱模。关键是“该软的时候软、该硬的时候硬”。")
bullet(doc, "溶剂浇铸：把材料溶于酒精一类溶剂，倒在平整模具上让溶剂挥发成膜。"
            "虫胶、生漆、硝化纤维素都可用此法。")
bullet(doc, "层压：布/纸浸胶后层层叠压，强度远高于同厚度的纯塑料件。")
bullet(doc, "后加工：车削（用脚踏车床，与册 11 天轴传动联动）、打磨、钻孔、染色。")
bullet(doc, "增塑思路：加入樟脑、蓖麻油、甘油一类物质可让硬脆的材料变柔韧，"
            "但用量靠打样，加多了会永久发黏。")

h1(doc, "八、安全与风险")
bullet(doc, "硫磺粉尘与硫化烟气刺激呼吸道，硫化工序须通风；含铅助剂（铅丹一类）有剧毒，尽量不用。")
bullet(doc, "甲醛、苯酚、混酸、硝酸蒸气均属高危，必须有独立通风的作业棚，不得在居室内操作。")
bullet(doc, "硝化纤维素与赛璐珞严禁靠近火源与大量囤放，成品也应分小批存放于凉爽处。")
bullet(doc, "大漆过敏是普遍现象，初次接触者先在手腕小面积试涂，出现红肿即停止接触。")
bullet(doc, "【官府风险】大规模采购硫磺、硝石会被与火药联系起来（见册 15）。"
            "做橡胶厂不要同时囤这两样，分开进、分开存。")

h1(doc, "九、实施顺序建议")
bullet(doc, "第一步：先建生漆与虫胶线（零化工基础，最快出商品）。")
bullet(doc, "第二步：硫酸稳定供应后（册 28），再考虑硬化酪蛋白。")
bullet(doc, "第三步：硝酸也稳定后，才碰赛璐珞，且必须单独建通风工棚。")
bullet(doc, "橡胶硫化取决于能否搞到胶源：有胶源则优先级提到第一，无胶源则先跳过，"
            "用漆布与皮革凑合。")

