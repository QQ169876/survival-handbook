h1(doc, "三、主线一：橡胶硫化（弹性件的唯一解）")
h2(doc, "① 为什么必须硫化")
bullet(doc, "【科学】生胶遇热发黏、遇冷变脆，原因是线型聚异戊二烯分子之间没有连接点，受热即滑动。")
bullet(doc, "硫化的本质是用硫在分子链之间搭“桥”（交联），把线型变网状——从此受热不流淌、受冷不发脆。")
bullet(doc, "【史实】固特异于 1839 年发现橡胶与硫共热后的硫化现象，这是第一种真正意义上的弹性材料工业化。")

h2(doc, "② 工艺步骤（只给流程与判据，不给配比）")
bullet(doc, "原料处理：胶乳加酸或静置凝固成块，反复水洗除蛋白与杂质，压成片、晾干。"
            "杂质是硫化失败与发霉的主因，宁可多洗。")
bullet(doc, "配炼：在生胶里混入硫磺与助剂，用石碾或木杵反复辊压、捶打至均匀。"
            "混合不均是本地硫化最常见的失败原因——肉眼可见的硫磺黄斑说明没混开。")
bullet(doc, "成型：趁可塑时压入木模或涂覆在布胎上，做成垫片、带子、鞋底、管件。")
bullet(doc, "硫化：在 130~150℃ 区间保持一段时间。过低不硫化，过高会焦化发脆。"
            "古代没有温度计，只能用“滴水成珠”“纸片焦黄”一类经验判据，务必先做小块试片。")
bullet(doc, "硬橡胶：大幅提高硫的比例并延长加热，可得黑色坚硬、绝缘性极佳的硬胶（ebonite），"
            "适合做梳子、电器壳与工具柄。")
note(doc, "配比、温度与时长本册均不给具体数值：胶源、硫的纯度、加热方式三者任一变化都会改变结果，"
          "照抄数字没有意义。做法是——固定其他条件，只改一个变量，每次做一组试片，破坏性检验后再定工艺。")

