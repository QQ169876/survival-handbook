h1(doc, "一、三条路线")
figure(doc, os.path.join(IMG, "37_印刷三路线.png"), "图37  雕版、活字与套色")

h2(doc, "① 雕版（最先做的一条）")
bullet(doc, "【史实】现存有明确纪年的最早印刷品是唐咸通九年（公元 868 年）的《金刚经》，"
            "为雕版印刷，说明这项技术在唐代已相当成熟。")
bullet(doc, "流程：写样 → 上版 → 刻版 → 刷墨 → 覆纸 → 刷印 → 揭纸晾干。")
bullet(doc, "板材：梨木、枣木等纹理细密、软硬适中的木材，须干燥透、无节无裂。")
bullet(doc, "优点：一次刻成可长期保存、随时加印；对刻工识字要求不高（照字样刻即可）。")
bullet(doc, "缺点：每页一版，大部头书的板材与存放成本高。")

h2(doc, "② 活字（门槛在字库）")
bullet(doc, "【史实】北宋庆历年间毕昇发明泥活字，记载见于沈括《梦溪笔谈》；"
            "元代王祯在《农书》中记载木活字并创制转轮排字盘；金属活字（铜、铅）在朝鲜与欧洲大规模发展。")
bullet(doc, "流程：制字（刻或铸） → 造字盘 → 检字排版 → 固版 → 刷印 → 拆版归字。")
bullet(doc, "泥活字：刻泥为字、火烧令坚。【经验】泥字易损、着墨不匀，须小量试验证。")
bullet(doc, "木活字：木质需细密不变形，刻后须尺寸一致，否则排版高低不平。")
bullet(doc, "金属活字：需铸造工艺（与分册 04 冶炼联动），成本高，适合长期大批量。")
note(doc, "【史实·重要的历史教训】活字印刷在古代中国并没有取代雕版。"
          "原因很实在：汉字字库数量大，一套活字的制作与检字成本远高于直接刻一块版，"
          "而雕版还能存着反复印。技术先进不等于经济划算——这条对你所有产业决策都适用。")

h2(doc, "③ 套色与饾版")
bullet(doc, "【史实】明代发展出分版套印与饾版、拱花技术（胡正言《十竹斋笺谱》为代表），"
            "可印出多色与压凸效果。")
bullet(doc, "原理：一色一版，逐次套印；定位（规矩）决定成败。")
bullet(doc, "与分册 25（织物印花）在原理上同源：都是**分版、对位、逐次施加**。")

h1(doc, "二、印刷四要素：版、墨、纸、刷")
table(doc,
      ["要素", "要求", "常见毛病"],
      [["版", "字面平整、笔画清晰、深浅一致", "刻歪、深浅不一、木材开裂"],
       ["墨", "细、黑、不洇、不糊版", "颗粒粗、太稀洇纸、太稠糊版"],
       ["纸", "施胶适度、吸墨适中、厚薄匀", "未施胶则洇，施胶过头则不吸墨"],
       ["刷", "棕刷或布包，力度均匀", "用力不匀导致浓淡不一"]],
      )
bullet(doc, "墨：【史实】传统用松烟墨或油烟墨，与胶配制。墨要细到没有颗粒感，否则会糊版。")
bullet(doc, "纸：与分册 22 联动。印刷用纸比书写用纸要求更高——厚薄必须均匀。")
bullet(doc, "【经验】墨与纸必须配套试：同一块版，换纸可能就印糊了。每次换纸都要重新试刷。")

h1(doc, "三、算一笔账：什么时候做什么")
table(doc,
      ["情形", "选择", "理由"],
      [["同一内容印几十部以内", "手抄或雕版小批量", "活字字库成本收不回来"],
       ["同一内容印数百部以上、且可能再版", "雕版", "一劳永逸，可存版加印"],
       ["品种多、每种印量都不大、且长期持续", "活字", "字库摊薄后优势才显现"],
       ["需要多色图案", "套色分版", "与印花同原理"],
       ["需要大量发行（报纸、历书一类）", "先雕版起步，产业成熟后再上活字/金属活字", "渐进最稳"]],
      )
note(doc, "判断口诀：**重印次数多的用雕版，品种数量多的用活字。**"
          "如果两者都不占，那就别印，先抄。")

h1(doc, "四、活字字库：如果真要做")
bullet(doc, "先统计字数：把你最常印的内容（如历书、蒙学、医方）用到的字统计出来，按频次排序。")
bullet(doc, "先做高频字：最常用的几百个字能覆盖大部分文本，先做这批即可开工。")
bullet(doc, "备用字与补刻：冷僻字临时补刻，不要一开始就想做全字库。")
bullet(doc, "归字系统：转轮排字盘（【史实】王祯所创）按韵或笔画归字，检字速度决定排版效率。")
bullet(doc, "【经验】字身尺寸必须严格一致，这是活字能否用起来的硬门槛——需要靠模具或量规控制。")

h1(doc, "五、内容策略：先印什么最值钱")
bullet(doc, "历书与农书：【史实】古代历书需求稳定且量大，是最容易变现的印刷品。"
            "注意：私印历书在不少朝代属违禁，先查清法度（见分册 21 的法度一项）。")
bullet(doc, "蒙学课本：《三字经》《百家姓》《千字文》一类，需求刚性、复购稳定。")
bullet(doc, "医方与农技：口碑传播快，容易建立名声。")
bullet(doc, "契约与账册格式纸：成本低、需求巨大，是现金牛。")
bullet(doc, "佛经、道经一类：在古代是重要的大宗印刷需求，且有供养人出资的传统。")
note(doc, "风险提醒：印刷是**放大影响力**的工具，也因此最容易招来注意。"
          "印什么、印多少、给谁看，要先看法度与当地权力结构（分册 21 第五章）。")

