h2(doc, "步骤")
bullet(doc, "① 浸提：干昆布（海带）剪段，加 10~15 倍清水，微沸煮 2 小时（不要大火滚煮，会带出过多褐藻胶变粘）。")
bullet(doc, "② 滤清：麻布过滤，渣可再煮一遍。")
bullet(doc, "③ 浓缩：水浴或文火蒸发到糖浆状（约原体积 1/20）。温度控制在 100℃ 以内。")
bullet(doc, "④ 中和：缓慢加入草木灰浸出液（碳酸钾）或小苏打，边加边搅，至 pH 约 7（尝之酸涩感消失、鲜味变圆润）。")
bullet(doc, "⑤ 干燥：摊成薄层低温烘干（<70℃），或拌入少量干淀粉吸湿成粉。")
bullet(doc, "⑥ 保存：密封陶罐 + 石灰干燥剂。")
note(doc, "这条路线产物是'粗鲜味粉'：含谷氨酸钠、甘露醇、褐藻糖胶与盐分，鲜味纯度低且带海腥味，"
          "但胜在安全、取材容易、当天就能出产品。拌入香菇粉直接当鲜味料卖，也完全够用。")

h1(doc, "四、标准路线：面筋酸水解制味精")
para(doc, "这是真正的工业化路线，也是池田菊苗 1908 年之后的主流工艺。核心原理四步："
          "把蛋白质打断成游离氨基酸 → 用等电点把谷氨酸单独析出 → 转成钠盐 → 结晶提纯。")
h2(doc, "① 制备面筋（谷氨酸的载体）")
bullet(doc, "和面：面粉加淡盐水揉成面团，静置 30 分钟让面筋网络形成。")
bullet(doc, "水洗：在清水中反复揉搓冲洗，淀粉被洗走，剩下灰白色有弹性的湿面筋（ gluten，蛋白质含量约 75%）。")
bullet(doc, "湿面筋中谷氨酸残基占比极高（约 30%+），是所有常见原料里最理想的来源。洗出的淀粉水沉淀后可得小麦淀粉，副产不浪费。")
h2(doc, "② 盐酸从哪来（前提工程）")
bullet(doc, "古代没有盐酸，但可以现制：食盐 + 浓硫酸共热，产生氯化氢气体，用水吸收即得盐酸。")
bullet(doc, "硫酸来源见分册六：干馏绿矾（硫酸亚铁）得粗硫酸，陶器蒸发浓缩。")
bullet(doc, "装置：耐热的陶甑/陶罐作反应釜，导气管用陶管或竹管（内衬桐油），吸收瓶用陶瓮装冷水，管口略浸入水面下防倒吸。")
note(doc, "氯化氢气体剧毒且有强腐蚀性，整套装置必须在露天、上风向操作，人站上风处，口鼻用湿布（蘸弱碱水）遮护。"
          "尾气用石灰水吸收中和。这一步风险最高，宁可慢，不可省。")
h2(doc, "③ 水解")
bullet(doc, "配比：湿面筋 : 约 15%~20% 稀盐酸 ≈ 1 : 2（重量），装入陶瓮或铜釜。")
bullet(doc, "加热沸腾保持 6~10 小时，补水维持体积。终点判断：取少量水解液，加碱调至中性后不再浑浊（蛋白已彻底分解）。")
bullet(doc, "容器：忌用铁器（铁离子使产物发黑）；铜、陶、搪瓷类最佳。")
h2(doc, "④ 脱色与过滤")
bullet(doc, "水解液呈深褐色。加入活性炭（木炭经蒸汽活化效果更好）搅拌加热，吸附色素与腐黑物。")
bullet(doc, "趁热过滤（麻布 + 砂层 + 炭层三级滤床），得到淡黄至琥珀色的清液。")
h2(doc, "⑤ 中和至等电点，析出谷氨酸（核心一步）")
bullet(doc, "原理：谷氨酸在 pH 3.2（等电点）溶解度最低，会大量结晶析出，而其他氨基酸大多仍溶解——这就是分离的关键。")
bullet(doc, "操作：先用石灰乳粗调至 pH 4~5，滤去硫酸钙等沉淀；再用碱液（纯碱或小苏打水）精调至 pH 3.2。")
bullet(doc, "静置数小时至过夜，析出谷氨酸结晶；抽滤或布袋压滤分离，冷水洗一遍。")
bullet(doc, "没有 pH 试纸？用逐级稀释对比法：取小样分杯，加不同量碱，静置后看哪杯析晶最多，放大到整锅。这是土法找准等电点的可靠做法。")
h2(doc, "⑥ 转成谷氨酸钠")
bullet(doc, "粗谷氨酸加清水打成浆，缓慢加碱（纯碱/小苏打/烧碱）并搅拌，调到 pH 6.8~7.0。")
bullet(doc, "此时谷氨酸完全溶解，生成谷氨酸钠溶液。碱要少量多次，边加边测，过头会发苦发涩。")
h2(doc, "⑦ 浓缩结晶")
bullet(doc, "温度红线：全程水浴或减压蒸发，液温 <70℃。超过 120℃ 会脱水环化生成焦谷氨酸，彻底失去鲜味。")
bullet(doc, "浓缩至液面出现晶膜，停止加热，缓慢冷却，析出白色棱柱状结晶——这就是味精。")
bullet(doc, "母液可反复浓缩回收 2~3 次，最后剩下的深色母液含其他氨基酸，可作酱油风味料或肥料，不要浪费。")
h2(doc, "⑧ 干燥与保存")
bullet(doc, "晶体滤出后 60℃ 以下烘干（或摊开阴干），密封装瓶，放干燥处。味精本身吸湿性不算强，但仍需防潮。")

h1(doc, "五、发酵副产路线：搭酱油的便车")
bullet(doc, "酱油、豆豉、面酱在发酵过程中，米曲霉的蛋白酶会把大豆/小麦蛋白分解，游离谷氨酸含量可达 1%~1.5%。")
bullet(doc, "做法：取酱油清液（或酱醪压滤液），活性炭脱色 → 调 pH 至等电点 3.2 → 静置析出谷氨酸 → 后续同标准路线。")
bullet(doc, "优点：不需要强酸水解，风险低；缺点：产率低，要处理大量液体。")
bullet(doc, "更省事的做法：直接把酱油浓缩成'酱油粉'（喷雾做不到就摊薄烘干磨粉），本身就是含味精的复合鲜味料。")
note(doc, "这条路线最聪明的用法是'顺带'：你在做分册一（青霉素）或酿酒时本来就要培养曲和酵母，"
          "酱油作坊是同一套发酵基础设施的副产品，等于一份投入多份回报。")

h1(doc, "六、酵母抽提物：被忽略的天然增鲜料")
bullet(doc, "来源：酿酒/啤酒的废酵母（酒糟沉淀）、做馒头留下来的酵母泥。")
bullet(doc, "原理：酵母细胞在 50~55℃ 或高盐环境下会'自溶'，自身酶把蛋白分解成氨基酸和核苷酸，释放出浓郁的肉汤般鲜味。")
bullet(doc, "做法：酵母泥加 3%~5% 食盐，调 pH 5~6，50~55℃ 保温 24~48 小时（期间缓慢搅拌），然后升温到 80℃ 灭酶，过滤浓缩成膏或烘干成粉。")
bullet(doc, "特点：它同时含谷氨酸和核苷酸，自带相乘效应，鲜味厚实，是最像'高汤'的天然调味料。")
bullet(doc, "用途：直接当鲜味粉，或按 10%~20% 加入鸡精配方，能显著减少味精用量仍保持厚度。")

