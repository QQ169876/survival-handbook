h2(doc, "鸡肉粉怎么来")
bullet(doc, "熬汤法：鸡架/鸡肉加水长时间熬煮，滤去油脂，汤液浓缩后拌入少量淀粉摊薄烘干，磨粉。")
bullet(doc, "直接法：鸡肉煮熟撕碎，小火焙干（或炭火烘干），磨粉过筛。带一点鸡油更香，但更易酸败。")
bullet(doc, "注意：肉粉含水或油都极易哈喇变质，必须彻底干燥（掰断有声），并尽快用完。")
h2(doc, "工艺要点")
bullet(doc, "所有组分必须充分干燥，分别磨成细粉（越细越不易分层，口感越好），过细筛。")
bullet(doc, "干混：按量在干燥容器中充分搅拌（大批量用木铲翻拌十分钟以上）。")
bullet(doc, "造粒：喷少量鸡油或浓糖浆作黏合剂，边拌边搓，形成小颗粒（鸡精的'颗粒感'就是这样来的），再低温烘干。")
bullet(doc, "包装：双层纸包 + 陶罐，罐内放一小包生石灰（用纸包好，不可直接接触产品）吸潮。")
note(doc, "鸡精最大的敌人是受潮：吸湿后会结块、发热、发霉。南方梅雨季必须小批量生产、快速周转，"
          "或在配方里多加些盐和糖（二者都能降低吸湿性并抑菌）。")
h2(doc, "素鲜粉版本")
bullet(doc, "去掉鸡肉粉与鸡油，改用：干香菇粉 8、黄豆粉（炒熟）6、笋干粉 3、酵母抽提物 3，其余盐糖比例不变。")
bullet(doc, "鲜味依靠 MSG + GMP 相乘，同样厚重；且更耐储存、成本更低、受众更广（寺院、素食者都能卖）。")

