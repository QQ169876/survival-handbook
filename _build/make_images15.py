# -*- coding: utf-8 -*-
"""生成分册 21 的示意图。"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_images import new, box, arrow, label, save  # noqa


def img35():
    im, d = new(900, 660, "图35  落地点评估：六个变量，而不是六个朝代")
    items = [("① 疾病", "医疗水平决定\n你的第一条命\n（最优先）"),
             ("② 口粮", "亩产与赋税率\n决定你能否\n活过第一个冬天"),
             ("③ 身份", "户籍、良贱、\n匠籍——决定你\n能不能自由行动"),
             ("④ 战乱", "是否处于\n战争周期与\n兵役征发范围"),
             ("⑤ 法度", "连坐、重刑、\n言论风险——\n决定试错成本"),
             ("⑥ 技术", "现有产业基础\n决定你手册里的\n技术能落地几成")]
    x = 40
    for i, (t, s) in enumerate(items):
        box(d, x, 90, 130, 60, t, fill=(255, 246, 225), outline=(170, 120, 30), fs=17)
        box(d, x, 165, 130, 175, s, fill=(240, 248, 235), outline=(60, 120, 60), fs=14)
        x += 143
    label(d, 40, 370, "朝代不是决定性变量：同一朝代，都城与边郡、盛世与末世，生存难度可以差十倍。", fs=16, color=(30, 100, 60))
    label(d, 40, 410, "优先级排序：疾病 > 口粮 > 身份 > 战乱 > 法度 > 技术。前两项不过关，后面全无意义。", fs=16, color=(170, 40, 40))
    label(d, 40, 450, "判断方法：先问自己落在哪里（城乡、战区与否），再问落在什么人身上（户籍、资产）。", fs=15)
    label(d, 40, 488, "网上的朝代评分表（几颗星）只能当谈资：它把几百年压成一个分数，信息量接近于零。", fs=15, color=(120, 120, 120))
    label(d, 40, 532, "真正可操作的是：抵达后 72 小时内查清——水源、粮价、户籍、官府距离、近期是否有战事。", fs=15, color=(30, 90, 160))
    label(d, 40, 576, "本册立场：不推荐朝代，只给评估框架。选错朝代死不了人，选错落地点会。", fs=16, color=(170, 40, 40))
    save(im, "35_落地点评估六变量.png")


if __name__ == "__main__":
    img35()
    print("done 35")
