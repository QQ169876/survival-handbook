h1(doc, "一、燃料先行：木炭窑")
para(doc, "木炭是古代冶铁的唯一现实燃料（煤炭含硫，会让铁热脆；焦炭工艺复杂）。冶铁 1 斤铁约耗炭 4~8 斤，"
          "先解决燃料再谈炼铁。")
bullet(doc, "窑型：土窑闷烧法——堆炭材（栎、柞、桦等硬木，直径碗口）成穹顶状，覆草抹泥封顶留烟口，点火后闷烧 3~5 天。")
bullet(doc, "判断：烟由白（水汽）转黄（焦油）再转清蓝（CO）时封烟口，全封闭冷却 2 天。")
bullet(doc, "好炭标准：黑色坚硬、敲击金属声、断面有光泽，'钢声炭'为上。")

