h1(doc, "四、六道基础菜（做法与判据）")
h2(doc, "① 蒸蛋羹")
bullet(doc, "蛋打散，加温水搅匀，滤去浮沫，碗口覆布或盖盘，上笼中火蒸。")
bullet(doc, "判据：表面平整如镜、轻晃中心不流动即熟；火太大或时间过长会起蜂窝。")

h2(doc, "② 白菜炖豆腐")
bullet(doc, "锅热下油，先煎豆腐至两面微黄，下白菜帮先炒软，再加叶，加水与盐焖煮。")
bullet(doc, "判据：豆腐入味、白菜软而不烂、汤汁乳白。")

h2(doc, "③ 红烧肉")
bullet(doc, "肉块冷水下锅焯去血沫，捞出洗净；锅中少油炒糖色（糖融化变琥珀色即下肉，不可等到发黑）。")
bullet(doc, "加水与调料，小火慢炖至筷子可轻松插入即成。")
