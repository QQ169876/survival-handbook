h2(doc, "② 粉食")
bullet(doc, "面团：面粉加水揉成团。水温决定口感——冷水和面筋道，温水和面柔软，开水烫面松软无筋。")
bullet(doc, "醒面：揉好盖湿布静置，让面筋松弛，之后更好擀开。")
bullet(doc, "饼：擀成薄片，干锅或抹油锅烙，两面微黄起泡即可；也可贴于锅壁烤。")
bullet(doc, "馒头：面团发酵后搓圆上笼蒸，水开后上汽计时，蒸透即离锅防粘。")
bullet(doc, "面条：面擀薄切条，水开下锅，浮起后再稍煮即捞；切面后撒干粉防粘。")
bullet(doc, "汤圆：湿粉团包馅，搓圆下锅，浮起即熟。")

h2(doc, "③ 发酵：老面最稳")
bullet(doc, "【史实】老面（面肥、酵头）续接是古代最普遍的发酵方式：每次留一小块面团做下次的种子。")
bullet(doc, "温度：温暖处发酵快，冷处慢。以面团体积膨大、内部呈蜂窝状为准。")
bullet(doc, "酸味：老面发酵会产生酸味，用碱中和。【经验】碱量按面团状态调，宁少勿多——"
            "多了成品发黄发苦，少了带酸。做法是少量加、揉匀、闻味、看色。")
bullet(doc, "判据：切面后气孔均匀；闻之无刺鼻碱味；蒸后不塌不黄。")

h1(doc, "三、家常菜：通用三段法")
para(doc, "绝大多数家常菜都可以拆成三段：爆香 → 主料断生 → 调味收汁。掌握这三段，菜谱就不用背了。")
