h2(doc, "媒染三法")
bullet(doc, "先媒染（最常用）：布先浸明矾液（约 5%~10%，温浸数小时或过夜），晾干后再入染缸。上色最匀。")
bullet(doc, "同浴媒染：染料与媒染剂同缸，省工序，但易生成沉淀浪费染料。")
bullet(doc, "后媒染：先染色再浸金属盐，用来调整或加深色相（例如把黄变成橄榄绿）。")
h2(doc, "单宁打底")
bullet(doc, "棉麻本身与金属盐结合力弱，先用五倍子或橡碗液浸泡（上单宁），再上金属盐，最后染色，牢度明显提升。")
bullet(doc, "这就是'单宁—金属—染料'三层结构，古代几乎所有深色棉布都走这条路。")

h1(doc, "三、靛蓝还原染色：最值得掌握的核心技术")
h2(doc, "为什么它最重要")
bullet(doc, "靛蓝是唯一能给出'洗不掉、晒不褪'深蓝的天然染料，且原料到处可种，成本极低。掌握了它，就掌握了古代最大宗的染色生意。")
h2(doc, "第一步：制靛（把蓝草变成可储存的靛泥）")
bullet(doc, "① 浸泡：新鲜蓝草茎叶入缸，清水淹没，压石防浮，夏 2 天、春秋 3~4 天。")
bullet(doc, "② 发酵判断：水变黄绿、起泡、叶软烂，捞去叶渣。")
bullet(doc, "③ 打靛：按水量加石灰乳（约为鲜叶重的 3%~5%），用木耙反复搅打翻腾 30~60 分钟，让空气充分进入——这一步是把溶解的靛苷转化成不溶靛蓝的关键。")
bullet(doc, "④ 沉淀：静置一夜，倒去上层清液，取底部深蓝沉淀，装入布袋滴干，即得靛泥（或直接做成靛蓝膏）。")
bullet(doc, "产出比：约 100 斤鲜蓝草得 2~4 斤靛泥。靛泥耐储存、耐运输，本身就是大宗商品。")
h2(doc, "第二步：建缸与还原")
bullet(doc, "配料：靛泥 + 草木灰碱水（提供碱性）+ 酒糟或米泔水（作为还原菌的养料）。也可加少量石灰。")
bullet(doc, "发酵：保持 20~30℃，每天搅动 1~2 次，2~4 天后缸液由蓝转黄绿，表面泛蓝紫色泡沫——这就是还原完成，靛蓝已变成可溶的靛白。")
bullet(doc, "健康的缸：黄绿色、带轻微酒香、搅动时泛蓝花。发黑、恶臭、长白膜说明缸坏了，须倒掉重起。")
h2(doc, "第三步：浸染与氧化")
bullet(doc, "布先用清水浸透并拧干，缓缓浸入缸液（不要搅浑底部沉淀），浸泡 10~30 分钟。")
bullet(doc, "取出、挤去液体、展开悬挂于空气中 15~30 分钟——此时可见由黄绿迅速变蓝，这是靛白被氧化回靛蓝。")
bullet(doc, "完成一次称'一水'。浅蓝 3~5 水，天蓝 6~10 水，深蓝 15~20 水。每水之间必须充分氧化，不能连续泡。")
bullet(doc, "染完用清水漂洗、晾干、皂洗或米汤浆一下，颜色更沉稳。")
note(doc, "养缸口诀：碱要够（灰水补）、温要稳（20~30℃）、菌要喂（每天少量酒糟）、搅要勤。"
          "老缸比新缸稳定得多，染缸是最值得长期维护的资产。")

h1(doc, "四、套染与拼色")
bullet(doc, "蓝 + 黄 = 绿：靛蓝打底（3~5 水）→ 再套槐花或栀子黄。这是古代唯一的绿色路线。")
bullet(doc, "红 + 蓝 = 紫：先茜草红（铝媒染）→ 再轻套靛蓝。色相由两者比例控制。")
bullet(doc, "红 + 黄 = 橙：茜草（钙媒染得橙红）+ 栀子。")
bullet(doc, "加深与压暗：任何颜色最后轻套一遍单宁铁，都会变深变暗（做玄、缁、褐等正色常用）。")
bullet(doc, "打样原则：每次套染前先用小样试色并记录配比，成功后再放大。没有记录就等于每次从零开始。")

