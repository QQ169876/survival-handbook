h1(doc, "六、色牢度与检验")
bullet(doc, "日晒：样布半遮曝晒 7 天，对比遮盖部分，褪色分级。靛蓝最优，直接性黄类最差。")
bullet(doc, "水洗：皂角水或草木灰水搓洗 3 次，看掉色程度与白布沾色。")
bullet(doc, "摩擦：白布干湿各擦 10 次，看沾色。浮色没洗净的布一擦就掉，属于不合格品。")
bullet(doc, "分级定价：按牢度与色相深浅分三等，好色高价、次色低价，明码标价反而更好卖。")

h1(doc, "七、安全与环保")
bullet(doc, "重金属：胆矾（铜）、锡盐均有毒，操作戴手套，废液不得排入饮用水源或灌溉渠，应挖渗坑自然沉降并覆土。")
bullet(doc, "强碱：草木灰水与石灰乳腐蚀皮肤，溅入眼立即大量清水冲洗。化石灰时放热，缓慢加水并搅拌。")
bullet(doc, "发酵气体：靛缸发酵会产生二氧化碳等，地窖式染坊要保持通风，入窖前先通风测试。")
bullet(doc, "染缸卫生：腐坏的染液滋生杂菌，污染布匹并产生恶臭，坏缸及时倒掉并对缸体消毒（沸水烫 + 日晒）。")
bullet(doc, "虫红与虫胶处理：动物性染料易招虫与霉，干燥、密封、加少量樟脑或花椒同储。")

