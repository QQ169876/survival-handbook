h1(doc, "六、四周落地顺序")
bullet(doc, "第 1 周：只用现成的破布麻头做一批，目标是把流程跑通，不追求质量。")
bullet(doc, "第 2 周：做竹帘与帘床，解决抄纸工具；同时试石灰蒸煮的时间。")
bullet(doc, "第 3 周：试纸药，把纸做匀；做压榨与焙墙，解决干燥。")
bullet(doc, "第 4 周：做施胶与砑光，把纸做到能写不洇；开始为分册 23 的印刷备料。")
bullet(doc, "长期：把楮树或麻的种植纳入农业规划，原料自给后成本会大幅下降。")

h1(doc, "七、红线")
note(doc, "一、石灰、草木灰碱液有腐蚀性，操作时护手护眼。\n"
          "二、蒸煮产生的高温碱液与蒸汽危险，锅具要稳妥、场地要通风。\n"
          "三、干燥用火墙时注意防火，纸是最易燃的东西之一。\n"
          "四、本册不给任何固定的蒸煮时间、碱量与配比，须按原料现场试。\n"
          "五、纸的价值在于规模化：单张手工纸没有竞争力，先把产量做起来。")

