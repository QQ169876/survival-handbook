h1(doc, "七、甘蔗制糖：标准流程")
figure(doc, os.path.join(IMG, "11_制糖流程.png"), "图 7-2  从榨汁到白糖的完整链条")
h2(doc, "① 榨汁")
bullet(doc, "工具：硬木双辊（立式石碾/木碾），畜力牵引。辊面刻浅槽增加咬入。")
bullet(doc, "复榨：蔗渣洒少量水再压一遍，可多回收 10%~15% 糖分。压第三遍收益递减。")
bullet(doc, "安全：喂料用木片推，绝不能用手——辊子卷入是绞断手臂级别的伤害。")
h2(doc, "② 澄清（决定成败的一步）")
bullet(doc, "蔗汁易发酵变酸，必须在榨出后几小时内加热处理。")
bullet(doc, "加石灰乳（熟石灰调水）中和有机酸并使杂质絮凝，每百斤汁加 0.3~0.6 斤，分次少量加入，边加边搅边尝（酸味消失即可）。")
bullet(doc, "煮沸后持续撇去浮沫——撇得越干净，糖色越浅。")
note(doc, "石灰过量会把蔗糖分解成不能结晶的转化糖，最后只能得到永远不出砂的糖稀。宁少勿多。")
h2(doc, "③ 熬煮浓缩")
bullet(doc, "连环锅：3~5 口锅一字排开，汁从最远处（最稀）依次舀到最近火处（最浓），连续作业效率最高。")
bullet(doc, "终点判断：糖浆沸点达 116~118℃；没有温度计时——滴一滴到冷水里能搓成软珠、或用筷子挑起拉丝不断即可起锅。")
bullet(doc, "控制火候：后期极易糊底，转小火并持续搅动。焦一次整锅报废。")
h2(doc, "④ 打砂（红糖/黑糖）")
bullet(doc, "糖膏起锅倒入浅盆或糖床，快速而持续地搅拌散热，促使形成细密晶体。")
bullet(doc, "冷却后即得红糖/黑糖——含糖蜜，颜色深、保湿、可直接卖，也是酿酒的好原料。")
h2(doc, "⑤ 分蜜脱色：黄泥水淋法（古法白糖）")
bullet(doc, "工具：'糖漏'——锥形陶器，底部开小孔。装入褐色糖膏，孔先用草塞住，静置让其初步结晶。")
bullet(doc, "操作：拔开底孔塞，顶部覆盖厚 3~5 cm 的湿黄泥浆，保持泥浆湿润。泥浆中的水缓慢下渗，溶走糖蜜与色素。")
bullet(doc, "时间：7~15 天。完成后上层雪白（白糖），下层仍黄褐（红糖），切开分层取用。")
bullet(doc, "原理：泥水形成的缓释水流相当于最原始的'洗糖'层析，同时泥浆细颗粒吸附色素。这是中国古代真实记载的工艺。")
bullet(doc, "收集流出的糖蜜：可酿酒（朗姆思路）、做醋、做糕点。")

h1(doc, "八、冰糖：静置缓慢结晶")
bullet(doc, "配液：白糖加水重溶，煮到饱和（约 75% 浓度，微微沸腾时糖液挂勺），过滤去杂。")
bullet(doc, "挂种：在液面下吊一根棉线或插竹签作为晶核（或用一小粒成品冰糖作种子）。")
bullet(doc, "静置：加盖纱罩防尘防虫，放在温度稳定、无人打扰处，7~15 天不动不移不搅。")
bullet(doc, "采收：取出晶体，晾干。母液可再熬浓重复结晶。")
note(doc, "结晶失败的两大原因：一是溶液不够饱和（再熬浓一点），二是被震动或温度骤变（换个安静角落）。")

h1(doc, "九、没有甘蔗怎么办：麦芽饴糖")
para(doc, "这是最被低估的方案。不需要甘蔗、不需要引进作物，只要有谷物和水，靠酶就能把淀粉变成糖。"
          "中国古代的'饴'就是这么来的。")
figure(doc, os.path.join(IMG, "12_糖化与结晶.png"), "图 7-3  麦芽糖化与冰糖结晶装置")
h2(doc, "步骤")
bullet(doc, "① 制麦芽：大麦（小麦也行）浸水一夜，摊在湿布上保持湿润，3~5 天发芽至芽长≈麦粒长，取出捣碎。")
bullet(doc, "② 备料：米饭、粟米、薯类、玉米糊蒸熟，摊凉到 60~70℃（手放进去能忍受但明显发烫）。")
bullet(doc, "③ 糖化：麦芽碎与熟料按约 1:5 拌匀，保温 60~70℃ 静置 2~4 小时，中间保持温度勿降温。")
bullet(doc, "④ 检验：取一点液体，不变蓝（无碘酒时与生米汤对照）——说明淀粉已转化。")
bullet(doc, "⑤ 过滤熬浓：滤出糖液，文火熬到粘稠即成饴糖（麦芽糖浆）。")
note(doc, "温度红线：超过 80℃ 淀粉酶永久失活，整锅变回一坨没甜味的糊糊。全程'手试微烫不灼'为准。")
h2(doc, "能用来做什么")
bullet(doc, "直接食用、做糕点糖果防腐剂（糖渍果品）。")
bullet(doc, "药丸赋形剂（蜜丸/糖丸），配合分册一的青霉素做成易于服用的丸剂。")
bullet(doc, "发酵原料：糖化液加酒曲直接酿酒，再进一步制醋。")
bullet(doc, "甜度约为蔗糖 40%，量大即可，是北方最现实的糖来源。")

h1(doc, "十、甜菜制糖（北方补充）")
bullet(doc, "流程：洗净切片 → 70~80℃ 热水浸出（渗出，糖溶于水）→ 加石灰乳并通入二氧化碳（碳酸饱充）沉淀杂质 → 过滤 → 熬煮结晶。")
bullet(doc, "难点在'碳酸饱充'：需要 CO₂，可用石灰窑废气或发酵产生。工艺比甘蔗繁琐，但北方可用，且含糖率不低。")
bullet(doc, "简化替代：不做饱充，直接熬煮浸出液，能得到深色的粗糖浆，聊胜于无。")

