h1(doc, "二、海盐晒盐法（最省力，优先做）")
h2(doc, "选址三要素")
bullet(doc, "地形：平缓的泥质或泥沙质海滩/盐碱地，能筑埂蓄水，渗漏小（黏土最好，沙土要铺黏土夯实）。")
bullet(doc, "气候：蒸发量远大于降水量，旱季长、日照强、风大。连续阴雨就颗粒无收。")
bullet(doc, "潮位：有纳潮条件（高潮位能自流进水最好，否则人工挑水/风车提水）。")
h2(doc, "盐田布局")
bullet(doc, "分区：纳潮沟 → 一级蒸发池 → 二级蒸发池 → 调节池 → 结晶池，面积逐级缩小（约 10:5:3:1）。")
bullet(doc, "逐级浓缩：卤水靠自流或戽水依次推进，浓度逐级上升，绝不一步到位。")
bullet(doc, "结晶池：池底压实或铺碎贝壳/石板，便于刮盐且不带泥。深度 10~20 cm 即可。")
h2(doc, "操作要点")
bullet(doc, "浓度管理：海水约 3°Bé（盐度 3.5%），蒸发到 25~28°Bé 才进结晶池；中途 15°Bé 左右会析出石膏（硫酸钙），要撇掉。")
bullet(doc, "结晶：卤水表面出现'盐花'（漂着的细小晶体）时停止补水，让它长到 3~5 mm 再收。")
bullet(doc, "收盐：清晨（温度低、晶体不易重溶）用木耙集拢，堆成小丘。")
bullet(doc, "淋卤：盐堆静置一夜，让苦卤（含镁、钙的母液）自然流走——这一步决定盐苦不苦。")
bullet(doc, "干燥：摊在竹席/石板上晒 1~2 天，装陶缸或双层布袋防潮。")
note(doc, "苦卤（母液）绝不能倒回盐池或留在盐里：氯化镁吸湿发苦还会致泻。收集起来另作他用（可提取硝石、泻盐），"
          "或倒到远离盐田的低洼处。")

h1(doc, "三、煎炼法：淋卤与熬盐")
h2(doc, "什么时候用煎法")
bullet(doc, "阴雨季节、日照不足地区、内陆盐碱地、或者你急着要盐——煎法不受天气限制，但烧柴是硬成本。")
h2(doc, "淋卤（把稀薄的盐变成浓卤水）")
bullet(doc, "刮土：退潮后的滩面或盐碱地，刮取泛白的咸沙土（表层 1~2 cm 最咸）。")
bullet(doc, "淋卤池：木桶/土坑，底部铺竹席或稻草作滤层，上面装咸土压实，缓缓浇海水或淡卤。")
bullet(doc, "接卤：底部流出的是浓卤水。第一遍浓卤留下；稀卤再浇一遍循环提浓。")
bullet(doc, "检验：无波美计就用莲子/鸡蛋浮沉法——投入十粒莲子，浮起四粒左右说明浓度接近可煎；沉底说明太稀。")
note(doc, "可信度说明：莲子试卤是中国古代盐业确实使用过的经验方法，但它对莲子的选择（陈年莲子比重不同）、"
          "卤水温度都很敏感，'浮四粒'只是古人约定俗成的经验值，不是精确刻度。"
          "正确用法是：固定一批莲子作为你自己的标准，先用已知浓度的卤水标定它，再用于日常判断。")
h2(doc, "煎盐")
bullet(doc, "器具：铁锅（古代叫'牢盆'）最好，陶锅次之，浅口大直径蒸发快。搭连环灶：前面预热、后面结晶，节省燃料。")
bullet(doc, "火候：先大火煮沸，再中小火收干；出现大量结晶时转文火，防止锅底爆盐和焦糊。")
bullet(doc, "出锅：趁热捞盐，摊开晾干。锅底残留盐层等冷却后再铲，别硬敲坏锅。")
note(doc, "省力技巧：能晒就晒，晒到 20°Bé 以上再入锅煎，燃料消耗能降到十分之一以下。这是沿海盐户的标准做法。")

h1(doc, "四、井盐：内陆的长期王牌")
bullet(doc, "找盐线索：地表白霜（盐碱花）、盐泉露头、特定植物（盐蒿、盐爪爪、盐肤木）、动物常去舔舐的土坑、地名带'盐井/盐场'。")
bullet(doc, "凿井（顿钻法）：竹篾绳吊圆刃铁钻头，人力踏碓反复冲击破碎岩石，再下木石护壁。这是重资产工程，深度几十到几百米，以年计——除非长期定居，否则先找现成盐井或买卤。")
bullet(doc, "提卤：竹制汲卤筒底部装皮钱（单向皮阀），入卤自动灌满，提起自动关闭；地面用绞盘/天车（畜力）提拉。")
bullet(doc, "净化浓卤：加豆浆或石灰乳，煮沸撇沫，沉淀钙镁与泥沙——豆浆除石膏是中国古代的真实工艺。")
bullet(doc, "煎盐：若当地有天然气露头（'火井'），直接引火煎盐，成本碾压烧柴——四川自贡就是这么做的。")
bullet(doc, "副产：井盐卤常伴生胆水（硫酸铜），可制胆矾，正好是分册六做丹尼尔电池/电镀的原料。")

