bullet(doc, "粗盐加少量清水（刚好溶解所需，宁少勿多）→ 静置 → 三层麻布过滤 → 文火熬干。")
bullet(doc, "重复 2 次，杂质含量大幅下降。滤液（母液）留着下次洗盐用，别倒。")
h2(doc, "加碘——穿越者的护城河")
para(doc, "内陆地区缺碘会导致甲状腺肿（大脖子病）和儿童克汀病（智力发育障碍），这在古代山区是普遍现象。"
          "你只需一件小事就能建立声望：在盐里加碘。")
bullet(doc, "碘源：海带、紫菜、海藻、海绵等海产烧成灰（海藻灰含碘量最高），或沿海地区直接取海草灰。内陆可用含碘的硝土/盐井卤水（部分井卤天然含碘）。")
bullet(doc, "用量：极微量。把海藻灰按 1%~2% 比例与细盐拌匀即可，宁少勿多。碘过量同样有害。")
