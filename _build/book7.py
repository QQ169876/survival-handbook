note(doc, "安全边界：成年人每日碘需求约 150 微克，过量（长期每日毫克级）会引发甲状腺功能异常。"
          "没有称量条件时，颜色判断——盐略微带一点灰褐色即可，肉眼看到明显发灰就过量了。")

