data = json.load(io.open(DATA, encoding="utf-8"))

for i, name in enumerate(ORDER):
    secs = data.get(name) or []
    h1(doc, "%s、%s（%d 篇）" % ("二三四五六七八九"[i], name, len(secs)))
    para(doc, INTRO.get(name, ""))
    if name in CAUTION:
        note(doc, CAUTION[name])
    for s in secs:
        if s["篇"] in SKIP:
            continue
        h2(doc, s["篇"])
        for p in s["段"]:
            para(doc, p)

