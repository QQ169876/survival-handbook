note(doc, "通信的第一件事不是建塔、不是架线，而是约定一套双方都懂的码表。\n"
          "没有约定的信号只是噪声。码表越简单越可靠，先把三五种状态传清楚，再谈复杂内容。")

h1(doc, "一、手段对照：按距离与需求选")
figure(doc, os.path.join(IMG, "32_通信手段对照.png"), "图32  七种手段的距离与特点")
