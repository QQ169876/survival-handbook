h1(doc, "二、基础：先把码表做出来")
h2(doc, "① 设计码表的三条原则")
bullet(doc, "状态要少：先把安全 / 求助 / 集结 / 撤离这几种核心状态定死，宁少勿多。")
bullet(doc, "区分度要大：两种信号在视觉或听觉上差别越大越不容易误判。")
bullet(doc, "要有校验：重要信息重复发送并回执确认，收到方以约定方式回报。")

h2(doc, "② 一套最简码表示例")
table(doc,
      ["信号", "含义", "回执"],
      [["一长声（或一旗横举）", "一切正常", "同信号回报"],
       ["三短声（或旗画圈）", "有情况，注意", "同信号回报"],
       ["连续急响（或旗上下急挥）", "紧急求助，立刻来人", "同信号回报并出发"],
       ["烟直上（或旗举白）", "安全，可通行", "同信号回报"],
       ["烟散乱（或旗举红）", "有敌情，勿近", "同信号回报并后撤"]],
      )
note(doc, "示例只是模板。你必须和同伴一起演练若干次，确认每人都能正确发出与识别，"
          "否则码表等于不存在。")

h1(doc, "三、旗语与灯语：视距内最实用")
h2(doc, "① 旗语")
bullet(doc, "器材：一根长杆、一面（或两面）颜色鲜明的布旗。底色与背景反差越大越好。")
bullet(doc, "站位：站在高处、空旷处，背向天空或背向单一颜色背景，避免杂乱背景。")
bullet(doc, "动作幅度要大、节奏要清楚；每个动作之间留出停顿，便于辨认。")
bullet(doc, "两面旗可表达更多状态（左旗与右旗各自位置组合），但需要更多训练。")

h2(doc, "② 灯语与反光")
bullet(doc, "夜间用油灯或火把，配合遮挡板（手或木板）做出长短明暗。")
bullet(doc, "白天可用铜镜或磨光的金属片反射日光——【史实】古代已有利用反光传讯的记载，"
            "原理简单、距离可观。")
bullet(doc, "反光瞄准：把反光点投向目标方向，靠观察者的反馈微调。")

h1(doc, "四、声音：鼓、锣、号角")
bullet(doc, "【史实】鼓与号角在古代用于军中与乡里传警，可覆盖数里。")
bullet(doc, "低频（大鼓）传得远、穿透性好；高频（锣、号）辨识度高但衰减快。二者配合。")
bullet(doc, "节奏即内容：约定若干固定节奏，每种节奏对应一条含义。记住：它传的是编号，不是句子。")
bullet(doc, "接力：多个站点依次转播，可把信息传得更远，但每转一次就有一次出错可能，"
            "重要信息必须要求末端回执。")

h1(doc, "五、烽火与狼烟：唯一的远距离高速信道")
h2(doc, "① 它是什么")
bullet(doc, "【史实】烽火台是古代最成熟的长距离报警体系，沿边与沿路设台，逐台接力传递。")
bullet(doc, "【经验】所谓狼烟，历来解释不一，多指掺入特定燃料使烟色更浓更直的做法。具体配方无定论，"
            "当作历史名词看待即可，不必执着复原。")

h2(doc, "② 怎么建")
bullet(doc, "选址：高处、彼此可见、间距以肉眼能辨识烟火为准。逐段实地验证可见性。")
bullet(doc, "燃料：需能产生大量浓烟（湿柴、青草、油脂类）与明火（干柴）。烟用于白天，火用于夜间。")
bullet(doc, "值守：每台需常驻人员与常备燃料，并有明确的点燃规则（谁下令、什么情况点、点几堆）。")

h2(doc, "③ 局限")
bullet(doc, "只能表达预先约定的少数状态，不能传递具体内容。")
bullet(doc, "受天气影响极大：雨雾、大风、逆光都会失效。")
bullet(doc, "误报代价高：一次虚假警报会消耗大量人力，也会让体系失去信任。")

h1(doc, "六、信鸽与驿站")
h2(doc, "① 信鸽")
bullet(doc, "【史实】鸽子归巢的本能被人类利用了数千年，是古代可靠的中距离单向通信手段。")
bullet(doc, "【科学】原理是归巢本能，因此鸽子必须在两地分别养熟：把鸽子在甲地养大，带到乙地放飞，"
            "它才能回甲地。方向是单向的。")
bullet(doc, "风险：猛禽、天气、疲劳、迷向。重要信息应多鸽同发，内容重复抄写数份。")
bullet(doc, "饲养需要时间与粮食，属于长期投入，不是应急手段。")

h2(doc, "② 驿站与文书")
bullet(doc, "驿站体系是古代唯一能承载完整文书的方式，但成本极高，需要马匹、人员、道路与补给网络。")
bullet(doc, "文书要点：简明、编号、署名、日期、印信。重要文书多份分路发送。")
bullet(doc, "保密：可用约定暗语、隐写（米汤一类书写后显影的做法属传统经验，可靠性有限），"
            "以及最有效的——派可信的人。")

h1(doc, "七、电报：为什么排在最后")
bullet(doc, "【科学】电报需要电源、导线、开关与收信装置，原理并不复杂，但每一环都要工业基础支撑。")
bullet(doc, "依赖链：稳定的电（分册 06）、拉制导线（分册 04 的拉丝）、绝缘材料（漆、橡胶替代品、"
            "丝麻浸油）、以及持证的操作员。")
bullet(doc, "【史实】实用的电报系统在 19 世纪才出现，比蒸汽机还晚，这本身就说明了它的门槛。")
bullet(doc, "务实建议：在拥有电报之前，你的主干通信应当是烽火 + 快马 + 信鸽，"
            "这三者在古代已被充分验证。")
note(doc, "如果你真的做到了发电（分册 06）与拉丝（分册 04），"
          "那么点对点的短线路电报是值得一试的：先拉一条几百步的双线，用通断表示点划，"
          "把码表压到最短。但先别指望它撑起一个网络。")

h1(doc, "八、组织：比技术更重要的部分")
bullet(doc, "站点与人员：任何通信手段都需要有人值守。先定人、定值守制度、定补给，再建设施。")
bullet(doc, "演练：定期演练，记录每次传达的耗时与出错点。演练记录就是你的运维手册。")
bullet(doc, "备份：主干手段必须有备份。烽火失效时靠什么？快马被阻时靠什么？")
bullet(doc, "保密与身份：口令、信物、印信。通信越发达，泄密的面越大。")

h1(doc, "九、四周落地顺序")
bullet(doc, "第 1 周：与核心同伴定下最简码表（不超过五条），反复口头与动作演练。")
bullet(doc, "第 2 周：做旗与灯，完成视距内的旗语与灯语，实测可达距离并记录。")
bullet(doc, "第 3 周：定鼓号节奏，覆盖周边数里；建立回执制度。")
bullet(doc, "第 4 周：勘察并选定烽火台址，验证台间可见性；开始养鸽（长期事项）。")
bullet(doc, "长期：视产业基础决定是否推进电报；在此之前把驿站与文书制度做扎实。")

h1(doc, "十、红线")
note(doc, "一、码表未演练过就上阵，等于没有通信。\n"
          "二、重要信息必须回执，没有回执就当作没送到。\n"
          "三、烽火是报警手段，不要试图用它传复杂内容。\n"
          "四、信鸽是单向的，不要指望它带回消息。\n"
          "五、通信设施与人员是长期负担，建了就要养得起。\n"
          "六、涉密信物与口令要能随时更换。")

save(doc, OUT)
