h1(doc, "七、安全（纺织车间是最早的工业事故高发地）")
bullet(doc, "卷入伤害：皮带、齿轮、滚筒是主要危险源。所有传动件加装木护栏；禁止穿宽松长衣、留长发不束；严禁运行中检修。")
bullet(doc, "棉尘：长期吸入棉尘导致呼吸道疾病，厂房要高窗通风，梳棉区单独隔开并设除尘（水幕或布袋）。")
bullet(doc, "火灾：棉麻纤维极度易燃，且飞絮遇明火瞬间蔓延。严禁车间内明火照明与吸烟，灯具加罩，夜间留人巡查。")
bullet(doc, "噪声与疲劳：早期工厂工时极长，长期单调操作导致劳损。合理安排轮班，这不是仁慈而是产能。")
bullet(doc, "童工与用工：本手册不建议使用童工——既违背现代伦理，也会在当地招致恶评、影响长期经营。")

