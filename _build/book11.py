h1(doc, "二、第一台该做的机器：轧棉机")
figure(doc, os.path.join(IMG, "21_轧棉机与飞梭织机.png"), "图 11-2  锯齿轧棉机与飞梭织机")
h2(doc, "锯齿式（惠特尼，1793）")
bullet(doc, "结构：木箱内装一根密布钢丝钩（或木齿、竹齿）的滚筒，滚筒下方是间距小于棉籽的栅格，旁边配反向旋转的毛刷辊。")
bullet(doc, "原理：滚筒钩住棉纤维从栅格缝拖过，棉籽被挡下落；刷辊把纤维从钩上刷下，连续出棉。")
bullet(doc, "关键参数：栅格间隙必须小于棉籽而能让纤维通过——这是唯一需要反复试调的地方。")
bullet(doc, "效率：手摇式日处理数十斤，畜力或水力带动可达数百斤，是人工的 50 倍以上。")
h2(doc, "简易替代：辊式轧棉机")
bullet(doc, "两根硬木辊（或一木一铁）对碾，籽棉喂入后被挤压拉过，棉籽被挤在辊前落下。")
bullet(doc, "效率较低、只适合长绒棉，但材料易得、木匠当天就能做出来，适合短期救急。")

h1(doc, "三、主力机器：珍妮纺纱机（优先做这个）")
figure(doc, os.path.join(IMG, "20_珍妮纺纱机.png"), "图 11-1  珍妮纺纱机结构：一个轮子带动一排锭子")
h2(doc, "为什么是它")
bullet(doc, "全木结构 + 少量铁件，无需机床加工；一个熟练木匠就能复制；效率提升 8 倍起步且可扩展到 80 锭。")
bullet(doc, "它不需要水力（手摇即可），可以立即在家庭作坊推广——这是它当年迅速普及的原因。")
h2(doc, "结构")
bullet(doc, "机架：硬木框架，底部四脚稳重。")
bullet(doc, "传动：手摇大轮 → 绳/皮带 → 一根长轴上装多个小轮（锭轮），一一带动各锭子。")
bullet(doc, "喂入：粗纱条从罗拉喂入，由活动夹棍夹住。")
bullet(doc, "工作节拍：夹棍先夹持外移把纱拉出（此时锭子转动加捻）→ 夹棍回程，锭子继续转把纱卷绕成管纱。")
h2(doc, "制作要点")
bullet(doc, "锭子：木杆上端削尖，下端装锭轮；必须直、转动同心，否则纱会抖。轴孔用硬木（枣、檀、黄杨）作轴承。")
bullet(doc, "锭轮与传动比：锭子转速需要几百转/分，靠大小轮比实现（手轮 1 转 → 锭子 5~10 转）。")
bullet(doc, "润滑：轴孔滴油（植物油即可），每日检查。")
bullet(doc, "张力：夹棍夹持力要均匀，太紧断纱、太松不起捻。")
h2(doc, "升级路线")
bullet(doc, "水力纺纱机（阿克莱特）：用罗拉连续牵伸代替夹棍，纱更结实但较粗，需要水力或畜力驱动。")
bullet(doc, "骡机（走锭精纺机）：珍妮 + 罗拉结合，能纺出既细又结实的纱，是棉纱质量的巅峰——但机构复杂，留到后期。")

h1(doc, "四、织造端：飞梭与动力织机")
h2(doc, "飞梭（凯伊，1733）——最划算的小改进")
bullet(doc, "原理：梭子底部装小轮，放在梭道里的打纬板上，操作者拉动两端绳索让梭子飞过梭口，并用打纬板把它'弹'回。")
bullet(doc, "价值：不再用手递梭，宽幅布一人可织，速度翻倍，且布幅不再受臂长限制。成本低到几乎可以忽略。")
h2(doc, "织造四机构（缺一不可）")
bullet(doc, "开口：综片（综框）上下分开经纱形成梭口；踏板联动两片综。")
bullet(doc, "投梭：飞梭带纬纱穿过梭口。")
bullet(doc, "打纬：筘（竹或木梳状）把纬纱推紧。")
bullet(doc, "卷取与送经：布卷到布轴上，经轴放出经纱，靠棘轮/棘爪保持张力恒定。")
h2(doc, "动力织机（进阶）")
bullet(doc, "把四机构用凸轮 + 曲柄 + 齿轮联动起来，由水力/畜力/蒸汽带动，一人看管数台。")
bullet(doc, "难点：各机构的时序必须精确（开口—投梭—打纬—卷取循环），加工精度要求骤增。")
bullet(doc, "建议：等珍妮机与水力传动跑通一年后再上，直接追求动力织机容易卡在调试上耗尽资源。")
h2(doc, "整经与上浆")
bullet(doc, "整经：把纱线按所需长度与根数平行卷到经轴上（整经架/整经滚筒），是织造前最大宗的准备工作。")
bullet(doc, "上浆：经纱刷米糊/面糊并烘干，减少织造时的摩擦断头。这一步对效率影响极大，别省。")

h1(doc, "五、动力：人力 → 畜力 → 水力")
bullet(doc, "人力：珍妮机手摇即可起步，零基础设施，最适合验证与初期推广。")
bullet(doc, "畜力：马匹带动转盘或 treadmill（踏车），功率约 300~500 W，适合多锭机与梳棉机。")
bullet(doc, "水力：最优解。水车 + 皮带/齿轮传动驱动天轴，再由天轴分头驱动各机器（这就是早期工厂的标准布局）。详见分册六。")
bullet(doc, "传动细节：天轴用长木轴 + 铸铁轴承座；各机器用皮带（皮革/多股麻辫）挂接，皮带打滑本身也是一种过载保护。")
note(doc, "工厂布局原则：所有机器沿一根天轴排开，动力源放在一端；皮带轮直径按所需转速配；"
          "预留可摘挂的皮带叉，方便单机检修而不影响全线。")

