h1(doc, "七、安全规程（每条都对应过真实事故）")
bullet(doc, "点火前：查水位、查安全阀（手动抬起确认能动作）、查易熔塞完好、查人孔与法兰无渗漏。")
bullet(doc, "运行中：坚守岗位，水位低于最低线立即压火停炉（严禁此时加水——冷水遇上干烧的红热金属会瞬间爆沸炸裂）。")
bullet(doc, "压力表失效或读数异常、焊缝/铆缝出现渗漏、炉体出现鼓包变形——全部立即停炉，冷却后再检修。")
bullet(doc, "机房：独立砖石建筑，屋顶轻质泄压（爆炸时向上泄而不是向四周），操作位与锅炉之间有遮挡。")
bullet(doc, "烫伤与机械伤害：裸露蒸汽管包麻布隔热；飞轮、皮带、曲柄全部加护栏；严禁在运行中擦拭或跨越转动部件。")
bullet(doc, "一氧化碳：燃煤锅炉通风不良会产生 CO，机房必须有对流烟囱与观察窗，人昏沉立即撤离。")

