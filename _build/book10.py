h1(doc, "二、原理：两种蒸汽机，先做哪一种")
figure(doc, os.path.join(IMG, "18_蒸汽机结构.png"), "图 10-1  纽科门大气压式蒸汽机结构与工作循环")
h2(doc, "纽科门机（大气压式，1712）——你的起点")
bullet(doc, "原理：不是蒸汽'推'活塞，而是蒸汽凝结成真空后，由大气压把活塞'压'下去。所以锅炉只需极低压。")
bullet(doc, "循环：进汽（活塞被配重拉起）→ 关阀喷冷水（缸内凝结成真空）→ 大气压压活塞下行做功 → 排水回到起点。")
bullet(doc, "优点：压力低（0.1~0.3 bar），锅炉风险小；汽缸精度要求相对宽松；结构简单，木铁混造都能跑。")
bullet(doc, "缺点：效率仅 0.5%~1%（蒸汽在冷缸里反复凝结，热量全浪费在加热缸壁上）；只能做往复直线运动，适合提水。")
h2(doc, "瓦特机（1765 起）——改进点，不是新原理")
bullet(doc, "独立冷凝器：让蒸汽在单独的容器里凝结，汽缸始终保持高温——这一项就把效率提高三到四倍。")
bullet(doc, "双动：蒸汽交替从活塞两侧进入，来回都做功（纽科门机只有回程做功）。")
bullet(doc, "蒸汽膨胀做功：进汽后提前切断，让蒸汽自行膨胀，节省蒸汽。")
bullet(doc, "曲柄连杆 + 飞轮：把往复运动变成旋转运动，这才是'通用动力'的关键（配飞轮储能、离心调速器稳速）。")
h2(doc, "高压机（特里维西克/早期机车）——暂不建议")
bullet(doc, "取消冷凝器、靠高压蒸汽直接做功，体积小功率大，但把风险全部转嫁给锅炉。没有现代材料与检测手段，不要做。")

h1(doc, "三、锅炉：真正决定生死的部分")
figure(doc, os.path.join(IMG, "19_锅炉与安全.png"), "图 10-2  锅炉结构、材料与安全三件套")
h2(doc, "材料选择")
bullet(doc, "铜板铆接最优：导热好、延展性好、不易脆裂，但昂贵。先用铜做一个小的验证机是明智的投入。")
bullet(doc, "熟铁板铆接次优：必须用无夹渣、无分层的优质熟铁（分册四的炒钢/块炼铁锻打件）。")
bullet(doc, "铸铁绝对禁止做受压件：铸铁抗拉强度低且脆，一旦超压会碎裂横飞，早期锅炉事故多源于此。")
h2(doc, "结构与工艺")
bullet(doc, "形状必须是圆筒（或圆柱 + 半球封头）：圆筒受力均匀，方箱在角上应力集中必然开裂。")
bullet(doc, "铆接：红热铆钉穿入孔中，一边顶住一边锻打钉头，冷却收缩使接缝抱死。孔要重合、钉距均匀。")
bullet(doc, "受热面：火焰接触面以下必须始终有水覆盖，一旦烧干（干烧），金属强度骤降，立即爆裂。")
bullet(doc, "水垢：硬水地区每运行数十小时就要除垢（醋酸浸泡或机械刮除）。水垢隔热导致局部过热是爆管主因。")
h2(doc, "安全三件套（做不出来就不要点火）")
bullet(doc, "安全阀：杠杆重锤式或弹簧式，调定在略高于工作压力处，超压自动排气。每次开机前手动抬起验证它没有锈死。")
bullet(doc, "易熔塞：在最低水位线附近的受热面上装铅锡合金塞，缺水干烧时先熔化泄压，是最后一道保险。")
bullet(doc, "水位计：玻璃管或连通管，随时能看到真实水位。看不见水位就等于闭着眼开车。")
note(doc, "必做测试：冷态水压试验——注满水，用手动泵加压到工作压力的 2 倍，保压 30 分钟无渗漏、无永久变形方可点火。"
          "每次检修后重做一次。这条规矩不能省。")
h2(doc, "压力分级（红线）")
bullet(doc, "低压 0.1~0.5 bar：纽科门机、蒸煮、采暖——这是你的工作区间。")
bullet(doc, "中压 1~3 bar：需要正规安全阀、持证司炉、定期测厚。谨慎进入。")
bullet(doc, "高压 5 bar 以上：无现代材料与无损检测手段，不做。")

h1(doc, "四、汽缸与活塞：精度的门槛")
h2(doc, "镗缸（最难的一关）")
bullet(doc, "要求：内孔圆、直、光洁。活塞与缸壁间隙过大则漏汽，过小则卡死。")
bullet(doc, "镗床：旋转的镗刀 + 稳定进给。刀头装在镗杆上，镗杆两端支承并旋转，工件或刀具之一作轴向进给。")
bullet(doc, "替代方案：先用铸铁或铜铸出带余量的缸筒，再用一系列逐级加大的铰刀/研磨具手工精修；用涂色法检查接触面。")
bullet(doc, "研磨：细砂 + 油脂 + 木质/铅质研磨具反复研磨，可提高光洁度并修正微小锥度。")
h2(doc, "活塞与密封")
bullet(doc, "结构：活塞略小于缸径，外缘开槽填入密封填料。")
bullet(doc, "填料：浸油的麻绳/大麻编织带（可更换、容错高）；进阶用皮革碗形密封；再进阶用金属活塞环（需更高加工精度）。")
bullet(doc, "润滑：动物脂、植物油，或石墨粉 + 油脂。活塞杆填料函要保持湿润，否则很快磨损漏汽。")
bullet(doc, "判断标准：手推活塞下行时应感到均匀阻力、无明显漏气声；用肥皂水涂接缝看气泡找漏点。")
h2(doc, "阀门与配汽")
bullet(doc, "早期：手动或机械联动的提升阀（锥形阀盘），靠凸轮/绳拉按节拍开闭。")
bullet(doc, "进阶：滑阀（D 形滑阀）由偏心轮驱动，自动配汽，是瓦特机的成熟方案。")
bullet(doc, "阀面要研磨贴合，漏汽会显著吃掉功率。")

h1(doc, "五、传动：从往复到旋转")
bullet(doc, "横梁摇杆：纽科门机的经典结构，一侧连活塞、一侧连泵杆，中间支点。输出仍是往复运动。")
bullet(doc, "曲柄连杆 + 飞轮：把往复变旋转。飞轮用重铸铁或石盘，储存能量使转动平稳（否则死点会卡住）。")
bullet(doc, "皮带/齿轮传动：把旋转输出到工作机。木齿轮、绳传动、皮带传动皆可（见分册六的增速机构）。")
bullet(doc, "离心调速器（瓦特的贡献之一）：两根带重球的摆臂随转速张开，通过套筒带动节流阀，自动稳定转速。这是自动控制的开端，结构简单且非常实用。")

