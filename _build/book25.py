h1(doc, "二、四条路线")
figure(doc, os.path.join(IMG, "39_印花四缬.png"), "图39  绞缬、蜡缬、夹缬、灰缬")

h2(doc, "① 绞缬（扎染）—— 零工具起步")
bullet(doc, "【史实】绞缬是古代最古老的防染技法之一，唐代「三缬」（绞缬、蜡缬、夹缬）之一，"
            "有出土实物佐证。")
bullet(doc, "做法：用线把织物按设计缝、扎、缚、夹，扎紧处染液进不去，拆线后露出白纹。")
bullet(doc, "变化：缝绞（用针线缝后抽紧）、扎绞（直接捆扎）、夹板绞（用木板夹紧）。")
bullet(doc, "优点：不需要任何专用工具，一块布一根线就能开工，最适合最先做。")
bullet(doc, "缺点：花纹难以完全重复，量产一致性差；靠手工熟练度。")

h2(doc, "② 蜡缬（蜡染）—— 冰纹是它的签名")
bullet(doc, "【史实】蜡缬同为唐代三缬之一，用蜡作防染材料，在西南少数民族地区长期传承至今。")
bullet(doc, "做法：熔蜡（蜂蜡、石蜡一类）用蜡刀或笔点绘在织物上，蜡冷却凝固后入染；"
            "染后加热脱蜡，露出白花。")
bullet(doc, "特征：蜡在揉染中会裂开，染液从裂缝渗入形成细密的「冰纹」——"
            "这是蜡染无法复制的标志性效果。")
bullet(doc, "【经验】蜡温是关键：太热会渗化失去边界，太冷则流不动、附着不牢。须反复试手感。")

h2(doc, "③ 夹缬（夹板防染）—— 最适合量产")
bullet(doc, "【史实】夹缬是唐代三缬中最接近「机械复制」的一种：两块雕有镂空花纹的木板把织物夹紧，"
            "染液只能从镂空处渗入，解开即成对称花纹。")
bullet(doc, "优点：同一套板可反复使用，花纹一致性高，最接近规模化生产。")
bullet(doc, "缺点：木版雕刻工作量大，且花纹受限于镂空结构（必须是连通的通道）。")
bullet(doc, "与分册 23 的雕版印刷共用木雕技术与工匠——**一套手艺，两处变现**。")

h2(doc, "④ 灰缬（蓝印花布）—— 明清民间的大宗")
bullet(doc, "【史实】蓝印花布是明清以来流传最广的民间印染工艺，"
            "用防染浆（传统以黄豆粉与石灰调制）通过镂空型版刮印在布上，"
            "干后染靛蓝，晾干刮去灰浆即成蓝底白花。")
bullet(doc, "关键材料：防染浆。豆粉提供黏性与成膜，石灰提供碱性并帮助附着——比例须按当地材料打样。")
bullet(doc, "型版：传统用多层桑皮纸裱成的镂空纸板（刷桐油防水），也可用薄木版或金属薄板。")
bullet(doc, "依赖分册 12 的靛蓝还原染色：蓝印花布必须有一口能正常发酵的靛缸才做得成。")
note(doc, "四缬入门顺序建议：**绞缬（零工具）→ 蜡缬（需蜡）→ 灰缬（需浆与型版）→ 夹缬（需木雕版）**。\n"
          "这一步步往上走，每一步都在给下一步攒工具与手艺。")

h1(doc, "三、进阶：媒染印花与拔染")
h2(doc, "① 媒染印花（用「药剂」印出颜色）")
bullet(doc, "【科学】原理很巧妙：先用不同的媒染剂（如明矾、绿矾一类）在布上印花，"
            "再整块入同一种染液；因为不同媒染剂与染料结合呈现的颜色不同，一处染液能显出多色。")
bullet(doc, "这是古代用**一次染色得到多色花纹**的办法，比分版套染效率高得多。")
bullet(doc, "【经验】媒染剂种类、浓度、与染料的匹配都须打样验证，本册不给配比。")
bullet(doc, "与分册 12 的媒染三法直接联动——先把媒染玩明白，再做媒染印花。")

h2(doc, "② 拔染（先染后拔）")
bullet(doc, "原理：先整块染色，再用能破坏色素的药剂局部「拔」去颜色，露出白花。")
bullet(doc, "【经验】古代可用的拔染手段有限，且对织物纤维损伤较大、边界控制困难。")
bullet(doc, "建议：把拔染当作**进阶探索**，先跑通四缬和媒染印花再考虑。")

h1(doc, "四、型版与对位：量产的两块基石")
bullet(doc, "型版材料：纸板（裱纸刷油，轻便宜做）、木版（耐用、可雕细节）、金属薄板（最耐用）。")
bullet(doc, "镂空结构：防染浆印花要求花纹是**断开的线段与点**（否则整块浆会脱落）；"
            "夹缬要求通道**连通**（否则染液进不去）。两者设计思路相反，不要混用。")
bullet(doc, "对位规矩：在多版套印或重复单元印花时，必须做固定的定位标记（规矩），"
            "否则花纹会错位。这是印花能不能量产的分水岭。")
bullet(doc, "【经验】重复单元的尺寸要与型版尺寸、织物幅宽匹配，先算好再刻版。")

