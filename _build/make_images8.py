"""分册八专用配图：味精（谷氨酸钠）制备、鲜味相乘与鸡精配方。"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from make_images import new, box, arrow, label, save, f


def img_msg():
    im, d = new(1000, 660, "图8-1  味精（谷氨酸钠）土法制备：面筋水解路线")
    steps = [("① 制面筋", "面团反复水洗\n洗出湿面筋"),
             ("② 酸水解", "面筋+稀盐酸\n回流/沸煮 6~10 h"),
             ("③ 脱色过滤", "活性炭吸附\n麻布滤清"),
             ("④ 中和结晶", "加碱调 pH 3.2\n析出谷氨酸"),
             ("⑤ 分离", "抽滤/离心\n得粗谷氨酸"),
             ("⑥ 转钠盐", "加碱调 pH 6.8~7.0\n生成谷氨酸钠"),
             ("⑦ 浓缩结晶", "低温蒸发\n结晶析出"),
             ("⑧ 干燥成品", "60℃ 以下烘干\n密封装瓶")]
    x0, y0, bw, bh, gap = 35, 92, 110, 92, 13
    for i, (t, s) in enumerate(steps):
        col = i % 4
        row = i // 4
        x = x0 + col * (bw + gap)
        y = y0 + row * (bh + 78)
        box(d, x, y, bw, bh, t + "\n" + s, fill=(238, 246, 238), outline=(40, 120, 70), fs=13)
        if col < 3:
            arrow(d, (x + bw + 2, y + bh / 2), (x + bw + gap - 2, y + bh / 2), color=(40, 120, 70))
        if row == 0 and col == 3:
            arrow(d, (x0 + bw / 2, y + bh + 4), (x0 + bw / 2, y + bh + 54))
            label(d, x0 + bw / 2 + 12, y + bh + 18, "转入中和阶段", fs=14, color=(90, 90, 90))
    label(d, 35, 300, "关键参数：", fs=18)
    for i, t in enumerate([
        "• 水解：面筋 : 稀盐酸(约 15~20%) ≈ 1 : 2，沸腾保持 6~10 小时，至取液滴入茚三酮/加热不变浑为止",
        "• 中和：分两步——先用石灰乳/草木灰水粗调至 pH 4~5 除硫酸根与杂质，再用碱精调到 pH 3.2（等电点）",
        "• 等电点：谷氨酸在 pH 3.2 溶解度最低，此时大量结晶析出，这是全法的核心原理",
        "• 转钠：粗谷氨酸加清水打浆，缓慢加碱（纯碱/烧碱）至 pH 6.8~7.0，谷氨酸即转为谷氨酸钠（味精）",
        "• 浓缩：温度务必 <70℃ 减压/水浴蒸发，过热会分解成焦谷氨酸（失去鲜味）",
    ]):
        label(d, 35, 335 + i * 34, t, fs=15)

    # 简易路线
    label(d, 35, 520, "简易替代路线（不碰强酸，建议先走这条）", fs=19, color=(20, 90, 140))
    box(d, 40, 556, 150, 62, "昆布/海带\n煮提 2 h", fill=(230, 242, 250), outline=(40, 90, 140), fs=15)
    arrow(d, (192, 587), (212, 587))
    box(d, 215, 556, 150, 62, "滤清并浓缩\n至糖浆状", fill=(230, 242, 250), outline=(40, 90, 140), fs=15)
    arrow(d, (367, 587), (387, 587))
    box(d, 390, 556, 150, 62, "加草木灰碱\n调 pH≈7", fill=(230, 242, 250), outline=(40, 90, 140), fs=15)
    arrow(d, (542, 587), (562, 587))
    box(d, 565, 556, 150, 62, "摊薄晾干\n得粗鲜味粉", fill=(230, 242, 250), outline=(40, 90, 140), fs=15)
    label(d, 740, 566, "纯度低、带海藻味，\n但零风险，可直接使用", fs=15, color=(30, 100, 60))
    label(d, 35, 628, "提示：水解法的盐酸可用'食盐+硫酸'法制取（硫酸来自分册六的绿矾干馏），这是本路线的前提。", fs=15, color=(170, 40, 40))
    save(im, "13_味精制备.png")


def img_chicken():
    im, d = new(1000, 560, "图8-2  鲜味相乘效应与鸡精配方")
    # 相乘示意
    label(d, 50, 62, "① 鲜味相乘：为什么 1+1 > 2", fs=19, color=(160, 60, 20))
    label(d, 60, 96, "鲜味强度（相对值，示意）", fs=15, color=(90, 90, 90))
    bars = [("味精 MSG", 100, (120, 170, 120)),
            ("香菇 鸟苷酸 GMP", 40, (150, 190, 150)),
            ("柴鱼/鱼干 肌苷酸 IMP", 40, (150, 190, 150)),
            ("MSG + IMP/GMP", 700, (220, 120, 40))]
    x, y = 60, 130
    for i, (name, v, col) in enumerate(bars):
        w = min(520, v * 0.7)
        d.rectangle([(x, y + i * 46), (x + w, y + i * 46 + 30)], fill=col, outline=(80, 80, 80), width=2)
        label(d, x + w + 12, y + i * 46 + 6, name + f"  ≈{v}", fs=16)
    label(d, 60, 340, "结论：味精里只要掺入少量干香菇粉或柴鱼/小鱼干粉，鲜味强度可提升 6~8 倍——这就是鸡精的真正底牌。", fs=16, color=(30, 100, 60))
    label(d, 60, 372, "同理：香菇炖鸡之所以鲜，正是谷氨酸（鸡肉/香菇）+ 核苷酸（香菇 GMP、鸡肉 IMP）的天然相乘。", fs=15)

    # 配方
    label(d, 620, 62, "② 鸡精参考配方（按重量份）", fs=19, color=(20, 90, 140))
    items = [("味精（谷氨酸钠）", "35~40", (250, 240, 220)),
             ("精盐", "30~35", (240, 240, 245)),
             ("细砂糖/葡萄糖", "8~12", (255, 250, 230)),
             ("鸡肉粉（烘干磨粉）", "8~10", (250, 230, 215)),
             ("干香菇粉（GMP 源）", "3~5", (245, 235, 215)),
             ("柴鱼/小鱼干粉（IMP 源）", "2~4", (245, 235, 215)),
             ("洋葱粉+大蒜粉", "1~2", (250, 245, 235)),
             ("白胡椒+姜粉", "0.5~1", (250, 245, 235)),
             ("鸡油/蛋黄粉（增香）", "1~2", (255, 245, 225))]
    y = 100
    for i, (name, pct, col) in enumerate(items):
        d.rectangle([(630, y), (960, y + 30)], fill=col, outline=(120, 120, 120), width=1)
        label(d, 640, y + 6, name, fs=14)
        label(d, 890, y + 6, pct + " 份", fs=14, color=(30, 80, 140))
        y += 34
    label(d, 620, 425, "工艺：各组分烘干→分别磨粉（越细越好）→过细筛→按量干混均匀", fs=15)
    label(d, 620, 452, "→ 用少量鸡油或糖浆作黏合剂造粒 → 低温烘干（<70℃）→ 密封防潮", fs=15)
    label(d, 620, 484, "注意：鸡精吸湿极强，必须双层纸包+陶罐+石灰干燥剂，否则半月结块变质", fs=15, color=(170, 40, 40))
    label(d, 60, 420, "素食版（素鲜粉）：去掉鸡肉粉与鸡油，改用干香菇+黄豆粉+笋干粉，", fs=15)
    label(d, 60, 447, "同样靠 MSG+GMP 相乘，鲜味不输荤版，且更易保存、受众更广。", fs=15)
    label(d, 60, 490, "盐的隐藏作用：少量盐本身能放大鲜味（钠离子协同），所以配方里盐不是凑数。", fs=15)
    save(im, "14_鸡精配方.png")


