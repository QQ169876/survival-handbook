h1(doc, "二、磺胺类：为什么走不通")
h2(doc, "① 它是什么")
bullet(doc, "【科学】磺胺类药物是最早一批人工合成的抗菌药，通过干扰细菌的叶酸合成起作用，"
            "对人的细胞影响相对小（人体不自行合成叶酸，需从食物摄取）。")
bullet(doc, "【史实】它于 20 世纪被发现并大规模用于战场与临床，在抗生素普及前救了大量生命。")

h2(doc, "② 为什么古代条件下不可行")
bullet(doc, "起始原料链太长：需要芳香胺、需要磺化与氯化试剂、需要氨。每一环在古代都要单独建立一套化工业。")
bullet(doc, "【科学】磺化与氯化步骤用到强腐蚀性、强毒性的试剂，产生的中间体与废气对人极危险，"
            "没有通风橱、耐酸器皿与防护，做一步伤一批。")
bullet(doc, "控温与分离：多步反应各有各自的温度区间与副反应，没有温度计与回流装置，只能靠运气。")
bullet(doc, "致命的是检验：你无法知道自己做出来的白色粉末里有多少是目标物、多少是有毒残留。"
            "吃下去的是药还是毒，分不清。")
note(doc, "真正的风险不是做不出来，而是做出来一点像样的白色结晶，然后你相信它是药。"
          "这是本手册最想拦住的一种错误。")

h2(doc, "③ 那为什么要知道它")
bullet(doc, "因为它解释了一件事：抗菌治疗的价值不在某一种药，而在对症与足量。")
bullet(doc, "在没有磺胺的年代，你的抗菌主力仍然是分册 01 的青霉素（也是高危，须严格按抑菌圈判据），"
            "以及更基础的：清创、引流、煮沸饮水、隔离病患。")
bullet(doc, "磺胺类知识的最大用处是让你明白，化学合成药这条路要等地基齐了再说，不要跳步。")

h1(doc, "三、水杨酸类：可以走，但要慢")
h2(doc, "① 历史与原理")
bullet(doc, "【史实】柳树皮用于退热止痛，在古代中国、古希腊、古埃及与北美原住民中都有记载，"
            "是少见的跨文明一致的经验。")
bullet(doc, "【科学】柳树皮含水杨苷，在体内与水解条件下可转为水杨酸；水杨酸经乙酰化后即现代常用的"
            "乙酰水杨酸（阿司匹林）。乙酰化的目的之一是减轻对胃的直接刺激。")
bullet(doc, "【经验】不同树种、不同季节、不同树龄的树皮含量差异很大，因此不能假定任何固定得率。")

h2(doc, "② 土法路线的四步（原理说明，剂量与得率一律不给）")
bullet(doc, "采集：选柳树（Salix 属，枝条柔韧、叶狭长）的嫩枝皮或根皮。春季与生长季采集较为常见。"
            "注意：只认准柳树，不要凭叶形相似随意采。")
bullet(doc, "提取：树皮剪碎，加水长时间煎煮，滤去渣，得到深色水提液。")
bullet(doc, "转化：水杨苷需水解为水杨酸。可用酸水解（需酸，见分册 08 的酸制备）或发酵法——"
            "【经验】发酵法条件温和但耗时长、杂菌难控。")
bullet(doc, "精制：酸化使游离水杨酸析出，过滤后用水重结晶。重结晶次数决定纯度，也决定收率，两者互相牺牲。")

h2(doc, "③ 判据：怎么知道自己做出来的是什么")
bullet(doc, "【科学】纯水杨酸有明确的熔点范围，可通过油浴粗略观察；不同物质熔点不同，可区分大部分杂质。")
bullet(doc, "【科学】水杨酸遇三价铁离子显紫色（酚类特征反应）。铁盐来自分册 04 的铁，或直接用铁锈溶于醋。"
            "这是一个可操作的定性判据——显色说明有酚类，不说明纯度。")
bullet(doc, "【经验】颜色洁白、无焦糊味、灼烧后残灰极少，是粗略的纯度参考，不能替代熔点与显色。")
note(doc, "判据的意义是排除明显错误，不是确认安全。即使全部判据都过，仍不知道含量。")

