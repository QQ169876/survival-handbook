h1(doc, "一、化学电源三兄弟")
figure(doc, os.path.join(IMG, "08_自制电池.png"), "图 6-1  三种自制电池")
h2(doc, "① 伏打电池（第一天就能做出来）")
bullet(doc, "材料：铜片、锌片（来源见下）、盐水/醋/柠檬汁浸透的布或纸，交替叠放（铜-布-锌-铜-布-锌……）。")
bullet(doc, "每单元 0.8~1.0V，串 6 单元≈5V。点亮 LED（若你带了）绰绰有余，也能做电镀、电解水演示。")
bullet(doc, "缺点：析氢极化严重，电流迅速衰减。间歇使用、多并几组可缓解。")
h2(doc, "② 丹尼尔电池（稳定版）")
bullet(doc, "锌棒浸硫酸锌（或稀硫酸）装在多孔陶罐里，陶罐放入铜容器，铜容器装硫酸铜溶液（胆矾——中药铺/颜料铺就有）。")
bullet(doc, "每单元 1.1V，电压稳定，可连续工作较久。是'给铅酸电池充电'的合格电源。")
h2(doc, "③ 铅酸电池（可充电，你的'电站'）")
bullet(doc, "结构：陶瓷/玻璃槽 + 稀硫酸（密度约 1.2，浓硫酸:水≈1:2 体积稀释，切记酸入水！）。")
bullet(doc, "极板：纯铅板（阴极）与过氧化铅板（阳极——新铅板先'化成'：用外部电源反复充放电数十次，表面氧化成深色）。")
bullet(doc, "单格 2.0V，三格串联 6V。充数百次没问题，是全系统的储能中枢。")
note(doc, "硫酸获取：干馏绿矾（硫酸亚铁 FeSO₄·7H₂O，天然矿物'皂矾'或钢渣副产品）于陶甑，冷凝得'矾油'"
          "（粗硫酸），陶器中蒸发浓缩。全程剧毒烟雾，露天下风操作，戴油布面罩护眼。这是古代真实存在的工艺（约 8 世纪），可行。")
h2(doc, "锌从哪来")
bullet(doc, "首选：拆现代物件——旧电池锌皮、镀锌铁片、黄铜（铜锌合金，效果打折）。")
bullet(doc, "土法：炉甘石（菱锌矿）+ 木炭在罐中还原可炼锌，工艺同炼铁，1100~1200℃（锌沸点 907℃，须冷凝收集——'蒸馏罐'法，中国明代已有）。")

h1(doc, "二、发电机：机械能变电")
figure(doc, os.path.join(IMG, "09_发电机结构.png"), "图 6-2  手摇发电机结构")
h2(doc, "原理一句话")
para(doc, "磁铁在线圈里转，线圈里就出电。电压与磁场强度、线圈匝数、转速三者成正比。"
          "定子绕线圈不动、转子带磁铁转，是最简单的结构。")
h2(doc, "材料清单")
bullet(doc, "磁铁：优先拆现代物件（耳机单元、喇叭磁钢、门吸、磁性包扣、马达）。天然磁石（磁铁矿块）太弱，只够做指南针。")
bullet(doc, "导线：漆包线 >丝包线 >生漆涂铜线。0.3~0.8mm 线径，总匝数几百到几千匝，绕够再试。")
bullet(doc, "绝缘替代：丝线密绕（古人做罗盘就是这么绝缘的）、大漆涂覆阴干、松香+蜂蜡浸渍。")
h2(doc, "制作要点")
bullet(doc, "增速：人力 60 转/分要变 600~2000 转/分，靠大轮带小轮的皮带传动（1:5~1:20）。转速是电压的生命。")
bullet(doc, "换向：转子装分段铜环换向器 + 石墨/炭棒电刷，输出脉动直流；或不管它，输出交流走外置整流（见分册五）。")
bullet(doc, "自励（无磁铁方案）：先用你的化学电池给定子励磁线圈通电建立磁场，发电机起电压后切换为自供电——'先点火，后自持'。")
h2(doc, "测量仪表（没有它们你两眼一抹黑）")
bullet(doc, "磁针电流计：指南针 + 外绕 50~100 匝线圈即成，看偏转方向判极性、偏转大小估电流。这是你的第一块'电表'。")
bullet(doc, "电压估算：电解水看气泡速率、看 LED 亮度/灯丝红白，经验化掌握。有条件用盐水电阻串分流。")

h1(doc, "三、常驻电站：让牛和水替你发电")
bullet(doc, "水力：小溪筑坝抬高 1~2 米落差，上游水槽引水冲击上射/下击式水轮，轮轴经齿轮/皮带增速驱动发电机。"
            "流量 0.1 m³/s × 落差 1.5 m × 效率 0.5 ≈ 700 W——一台够全作坊用。")
bullet(doc, "畜力：马拉大磨盘式水平大轮（直径 4~6 米），边沿带绳槽增速拉发电机。牛马力气大耐久，配专人看管。")
bullet(doc, "风力：木制风车（荷兰式或立轴式），配稳速与限速装置，防大风飞车。偏远水草丰茂处才值得。")
bullet(doc, "输电：作坊内 50 米内用铜/铁裸线沿瓷壶（绝缘子）架设；生漆、松香蜡、丝绳都是合格绝缘材料。远距离先升压？没有变压器，别拉远线。")

